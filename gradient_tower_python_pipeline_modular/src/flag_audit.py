def _bit_label(v: int) -> str:
    """Convert integer bitmask into a human-readable combination string."""
    v = int(v)
    if v == 0:
        return "UNFLAGGED"

    labels = [name for name, bit in FLAG_ORDER if (v & bit) > 0]
    unknown = v & ~ALL_BITS
    if unknown:
        labels.append(f"UNKNOWN_BITS_{unknown}")

    return "+".join(labels) if labels else "UNKNOWN"


def _mask_any_bit(values: np.ndarray, bits: Iterable[int]) -> np.ndarray:
    """Return boolean mask where at least one selected bit is active."""
    values = np.asarray(values, dtype=np.int64)
    out = np.zeros(values.shape, dtype=bool)
    for bit in bits:
        out |= (values & bit) > 0
    return out


