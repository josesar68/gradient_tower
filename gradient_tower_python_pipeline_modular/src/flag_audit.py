def convert_index_utc_to_local(
    df: Optional[pd.DataFrame],
    local_tz: str = "America/Lima",
    remove_timezone: bool = True,
) -> Optional[pd.DataFrame]:
    """Convert a DataFrame DatetimeIndex from UTC to a local timezone."""
    if df is None or df.empty:
        return df

    out = df.copy()
    out.index = pd.to_datetime(out.index)

    if out.index.tz is None:
        out.index = out.index.tz_localize("UTC")
    else:
        out.index = out.index.tz_convert("UTC")

    out.index = out.index.tz_convert(local_tz)

    if remove_timezone:
        out.index = out.index.tz_localize(None)

    out.index.name = "time"
    return out


def convert_index_utc_to_lima(df: Optional[pd.DataFrame], remove_timezone: bool = True) -> Optional[pd.DataFrame]:
    """Backward-compatible alias for the original function name."""
