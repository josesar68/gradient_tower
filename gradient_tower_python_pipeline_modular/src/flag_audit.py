def _compute_hard_fail_mask(flag_values: np.ndarray, hard_fail_bits: Iterable[int]) -> np.ndarray:
    """Compute hard-fail mask logic: RANGE OR (STEP AND SPIKE) OR active parameters."""
    flag_values = np.asarray(flag_values, dtype=np.int64)
    bits_tuple = tuple(hard_fail_bits) if hard_fail_bits is not None else ()

    hard_mask = np.zeros(flag_values.shape, dtype=bool)

    if BIT_RANGE in bits_tuple:
        hard_mask |= (flag_values & BIT_RANGE) > 0

    if BIT_STEP in bits_tuple and BIT_SPIKE in bits_tuple:
        hard_mask |= (((flag_values & BIT_STEP) > 0) & ((flag_values & BIT_SPIKE) > 0))

    if BIT_PERSIST in bits_tuple:
        hard_mask |= (flag_values & BIT_PERSIST) > 0

    if BIT_INCONSIST in bits_tuple:
        hard_mask |= (flag_values & BIT_INCONSIST) > 0

    return hard_mask


