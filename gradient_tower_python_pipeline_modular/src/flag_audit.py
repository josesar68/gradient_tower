def infer_samples_per_period(index: pd.DatetimeIndex, period: str = "30min") -> int:
    """Infer the expected number of samples per aggregation period.

    Uses optimized low-level properties (.asi8) to avoid deprecation warnings.
    """
    if len(index) < 2:
        return int(pd.Timedelta(period).total_seconds() // 60)

    dt_sec = np.diff(index.asi8) / 1e9
    dt_sec = dt_sec[np.isfinite(dt_sec)]
    dt_sec = dt_sec[dt_sec > 0]

    if len(dt_sec) == 0:
        return int(pd.Timedelta(period).total_seconds() // 60)

    sample_step_sec = int(round(np.median(dt_sec)))
    period_sec = int(pd.Timedelta(period).total_seconds())

    if sample_step_sec <= 0:
        return max(1, int(period_sec // 60))

    return max(1, int(round(period_sec / sample_step_sec)))


def sanitize_netcdf_name(name: str) -> str:
    """Convert a DataFrame column name into a safe NetCDF variable name."""
    return (
        str(name)
        .replace(" ", "_")
        .replace("/", "_")
        .replace("-", "_")
        .replace(".", "_")
        .replace("(", "")
        .replace(")", "")
    )


def get_variable_units(col: str) -> str:
    """Assign standard SI units matching the CF convention based on column prefixes."""
    col = str(col)
    if col.startswith("temp"):
        return "degree_C"
    if col.startswith("RH"):
        return "%"
    if col.startswith("wind"):
        return "m s-1"
    if col.startswith("dir_wind"):
        return "degree"
    if col.startswith("q_"):
        return "kg kg-1"
    if col.startswith("theta_v"):
        return "K"
    return "unknown"


def get_variable_long_name(col: str) -> str:
    """Assign descriptive metadata labels to variables written into the NetCDF."""
    col = str(col)
    if col.startswith("temp"):
        return f"air temperature statistics for {col}"
    if col.startswith("RH"):
        return f"relative humidity statistics for {col}"
    if col.startswith("wind"):
        return f"wind speed statistics for {col}"
    if col.startswith("dir_wind"):
        return f"wind direction statistics for {col}"
    if col.startswith("q_"):
        return f"specific humidity statistics for {col}"
    if col.startswith("theta_v"):
        return f"virtual potential temperature statistics for {col}"
    return f"statistics for {col}"


def detect_wind_direction_columns(df: pd.DataFrame, cfg: Optional[TowerConfig] = None) -> list:
    """Detect wind direction columns unrolling the TowerConfig maps safely."""
    if cfg is not None and hasattr(cfg, "wdir_cols"):
        return [col for col in cfg.wdir_cols.values() if col in df.columns]

    return [col for col in df.columns if str(col).lower().startswith("dir_wind")]


