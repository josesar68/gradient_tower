def _circular_diff_deg(a: pd.Series, b: pd.Series) -> pd.Series:
    """Minimum signed angular difference a-b in degrees in [-180, 180)."""
    return ((a.astype(float) - b.astype(float) + 180.0) % 360.0) - 180.0


def _circular_abs_diff_deg(a: pd.Series, b: pd.Series) -> pd.Series:
    """Minimum absolute angular difference in degrees."""
    return _circular_diff_deg(a, b).abs()


def _rolling_circular_center_deg(s: pd.Series, window: int, min_periods: Optional[int] = None) -> pd.Series:
    """Rolling circular center based on atan2(mean(sin), mean(cos))."""
    if min_periods is None:
        min_periods = max(3, window // 2)

    rad = np.deg2rad(s.astype(float))
    sin_mean = np.sin(rad).rolling(window, center=True, min_periods=min_periods).mean()
    cos_mean = np.cos(rad).rolling(window, center=True, min_periods=min_periods).mean()
    ang = np.rad2deg(np.arctan2(sin_mean, cos_mean)) % 360.0
    return pd.Series(ang, index=s.index)


def _rolling_circular_mad_deg(s: pd.Series, window: int, center_deg: Optional[pd.Series] = None, min_periods: Optional[int] = None) -> pd.Series:
    """Rolling circular MAD around a circular rolling center."""
    if min_periods is None:
        min_periods = max(3, window // 2)
    if center_deg is None:
        center_deg = _rolling_circular_center_deg(s, window=window, min_periods=min_periods)

    dev = _circular_abs_diff_deg(s.astype(float), center_deg.astype(float))
    return dev.rolling(window, center=True, min_periods=min_periods).median()


# =============================================================================
# 4. SEVERIDAD ROBUSTA MAD (Cálculos Vectorizados)
# =============================================================================

def _calculate_mad_severity(s: pd.Series, window: int) -> pd.Series:
    """Calculate robust spike severity for scalar variables: |x - median| / MAD."""
    if window < 3 or window % 2 == 0:
        raise ValueError("mad_window must be >= 3 and odd.")

    s = pd.to_numeric(s, errors="coerce")
    min_periods = max(3, window // 2)

    med = s.rolling(window, center=True, min_periods=min_periods).median()
    dev = (s - med).abs()
    mad = dev.rolling(window, center=True, min_periods=min_periods).median()

    return dev / np.maximum(mad, 1e-12)


def _calculate_circular_mad_severity(s: pd.Series, window: int) -> pd.Series:
    """Calculate robust spike severity for circular wind direction variables."""
    if window < 3 or window % 2 == 0:
        raise ValueError("mad_window must be >= 3 and odd.")

    s = pd.to_numeric(s, errors="coerce")
    min_periods = max(3, window // 2)

    center = _rolling_circular_center_deg(s, window=window, min_periods=min_periods)
    dev = _circular_abs_diff_deg(s, center)
    mad = _rolling_circular_mad_deg(s, window=window, center_deg=center, min_periods=min_periods)

    return dev / np.maximum(mad, 1e-12)


