def audit_flags_presence(
    flags_df: pd.DataFrame,
    data_df: Optional[pd.DataFrame] = None,
    columns: Optional[List[str]] = None,
    top_k_combos: int = 15,
    *,
    round_freq: Optional[str] = None,
    nearest_tol: Optional[str] = None,
    align: Literal["intersection", "union", "data_index", "flags_index"] = "intersection",
    assume_local_tz: Optional[str] = None,
    duplicate_policy: Literal["first", "last", "mean", "median"] = "first",
    hard_fail_bits: Optional[Iterable[int]] = None,
    mad_window: int = 21,
    include_all_cells_when_no_data_df: bool = True,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.Series, Dict[str, Any]]:
    """Audit QC flag presence, distribution, combinations, and hard-fail impact."""
    if not isinstance(flags_df.index, pd.DatetimeIndex):
        raise ValueError("flags_df must have a DatetimeIndex.")
    if data_df is not None and not isinstance(data_df.index, pd.DatetimeIndex):
        raise ValueError("data_df must have a DatetimeIndex.")

    bits_tuple = tuple(hard_fail_bits) if hard_fail_bits is not None else ()

    # 1. Normalización de tiempos
    F = _normalize_time_index(flags_df, assume_local_tz, round_freq, duplicate_policy)
    D = _normalize_time_index(data_df, assume_local_tz, round_freq, duplicate_policy) if data_df is not None else None

    # 2. Selección segura de columnas
    columns = _safe_flag_columns(flags_df=F, data_df=D, columns=columns, drop_non_flag_like=True)
    if not columns:
        raise ValueError("No valid columns to audit. Check configurations and source names.")

    F = F[columns]
    if D is not None:
        D = D[columns]

    # 3. Alineación Temporal
    if D is None:
        idx = F.index
        considered = pd.DataFrame(include_all_cells_when_no_data_df, index=idx, columns=columns, dtype=bool)
    elif nearest_tol is not None:
        D = D.sort_index()
        F = F.sort_index().reindex(D.index, method="nearest", tolerance=pd.Timedelta(nearest_tol))
        matched = ~F.isna().all(axis=1)
        F, D = F.loc[matched], D.loc[matched]
        considered = D.notna()
    else:
        if align == "intersection": idx = F.index.intersection(D.index)
        elif align == "union": idx = F.index.union(D.index)
        elif align == "data_index": idx = D.index
        elif align == "flags_index": idx = F.index
        F, D = F.reindex(idx), D.reindex(idx)
        considered = D.notna()

    F = F.apply(pd.to_numeric, errors="coerce").fillna(0).astype("int64")
    considered = considered.fillna(False).astype(bool)

    # 4. Auditoría a nivel de Celda
    per_col_rows = []
    for col in columns:
        mask_cons = considered[col].values
        flags_col = F[col].values
        n_cells = int(mask_cons.sum())

        rec = {"column": col, "cells_considered": n_cells}
        for name, bit in FLAG_ORDER:
            rec[name] = int((((flags_col & bit) > 0) & mask_cons).sum())

        rec["ANY"] = int((((flags_col & ALL_BITS) > 0) & mask_cons).sum())
        rec["UNFLAGGED"] = int(n_cells - rec["ANY"])

        hard_mask = _compute_hard_fail_mask(flags_col, bits_tuple) & mask_cons
        rec["HARD_FAIL"] = int(hard_mask.sum())
        rec["HARD_FAIL_pct"] = np.nan if n_cells == 0 else (100.0 * rec["HARD_FAIL"] / n_cells)

        # Diagnóstico robusto MAD integrado
        if D is not None and D[col].notna().any():
            try:
                is_wdir = str(col).lower().startswith("dir_wind")
                severity = _calculate_circular_mad_severity(D[col], mad_window) if is_wdir else _calculate_mad_severity(D[col], mad_window)
                spike_cells = (((flags_col & BIT_SPIKE) > 0) & mask_cons)
                
                if spike_cells.any():
                    vals = severity.values[spike_cells]
                    rec["spike_severity_mean"] = float(np.mean(vals))
                    rec["spike_severity_median"] = float(np.median(vals))
                    rec["spike_severity_max"] = float(np.max(vals))
                else:
                    rec["spike_severity_mean"] = rec["spike_severity_median"] = rec["spike_severity_max"] = np.nan
            except Exception:
                rec["spike_severity_mean"] = rec["spike_severity_median"] = rec["spike_severity_max"] = np.nan

        per_col_rows.append(rec)

    per_col_cells = pd.DataFrame(per_col_rows).set_index("column")
    for name in [n for n, _ in FLAG_ORDER] + ["ANY", "UNFLAGGED"]:
        per_col_cells[f"{name}_pct"] = 100.0 * per_col_cells[name] / per_col_cells["cells_considered"]

    # 5. Impacto temporal por Fila
    rows_total = len(F)
    rows_considered = int(considered.any(axis=1).sum())
    row_counts = []

    for name, bit in FLAG_ORDER:
        has_flag = np.any([((F[c].values & bit) > 0) & considered[c].values for c in columns], axis=0)
        row_counts.append({"flag": name, "rows_with_flag": int(has_flag.sum())})

    per_flag_rows = pd.DataFrame(row_counts).set_index("flag")
    per_flag_rows["rows_total"], per_flag_rows["rows_considered_total"] = rows_total, rows_considered
    per_flag_rows["rows_with_flag_pct_all_rows"] = 100.0 * per_flag_rows["rows_with_flag"] / rows_total
    per_flag_rows["rows_with_flag_pct_considered_rows"] = 100.0 * per_flag_rows["rows_with_flag"] / np.maximum(rows_considered, 1)

    # Hard fail a nivel de Fila
    has_hard = np.any([_compute_hard_fail_mask(F[c].values, bits_tuple) & considered[c].values for c in columns], axis=0)
    rows_with_hard = int(has_hard.sum())
    per_flag_rows.loc["HARD_FAIL"] = [rows_with_hard, rows_total, rows_considered, 100.0 * rows_with_hard / rows_total, 100.0 * rows_with_hard / np.maximum(rows_considered, 1)]

    # 6. Combinaciones de banderas celdas evaluadas
    vals_considered = F.values[considered.values]
    combos = pd.Series(vals_considered).map(_bit_label).value_counts().head(top_k_combos) if vals_considered.size > 0 else pd.Series(dtype="int64")

    # 7. Diagnósticos de metadata
    diagnostics = {
        "columns": columns, "n_columns": len(columns), "total_cells_considered": int(considered.values.sum()),
        "total_rows": rows_total, "align": f"nearest {nearest_tol}" if nearest_tol else align, "duplicate_policy": duplicate_policy
    }

    return per_col_cells, per_flag_rows, combos, diagnostics


