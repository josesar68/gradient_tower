def save_reconstructed_dataframes_pickle(
    cleaned_from_nc: pd.DataFrame,
    flags_from_nc: pd.DataFrame,
    raw_from_nc: Optional[pd.DataFrame] = None,
    out_dir: str = "output_df",
) -> Dict[str, str]:
    """Safely export reconstructed DataFrames to optimized binary pickle files."""
    os.makedirs(out_dir, exist_ok=True)
    outputs = {}
    items = {
        "cleaned_from_nc": cleaned_from_nc,
        "flags_from_nc": flags_from_nc,
        "raw_from_nc": raw_from_nc,
    }
    for name, df in items.items():
        if df is None or df.empty:
            continue
        path = os.path.join(out_dir, f"{name}.pkl")
        df.to_pickle(path)
        outputs[name] = path
    return outputs


