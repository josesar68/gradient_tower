def _dedup_index(
    df: pd.DataFrame,
    policy: Literal["first", "last", "mean", "median"] = "first"
) -> pd.DataFrame:
    """Resolve duplicated timestamps according to the selected policy."""
    if not isinstance(df.index, pd.DatetimeIndex):
        raise ValueError("The DataFrame index must be a DatetimeIndex.")

    if df.index.is_unique:
        return df

    if policy in ("first", "last"):
        return df[~df.index.duplicated(keep=policy)]

    if policy in ("mean", "median"):
        num = df.select_dtypes(include=[np.number]).groupby(level=0).agg(policy)
        non = df.select_dtypes(exclude=[np.number]).groupby(level=0).first()
        return num.join(non, how="outer").sort_index()

    raise ValueError("duplicate_policy must be one of: first, last, mean, median.")


def _normalize_time_index(
    df: pd.DataFrame,
    assume_local_tz: Optional[str] = None,
    round_freq: Optional[str] = None,
    duplicate_policy: Literal["first", "last", "mean", "median"] = "first"
) -> pd.DataFrame:
    """Normalize time index structure and timezone characteristics safely."""
    if not isinstance(df.index, pd.DatetimeIndex):
        raise ValueError("The DataFrame must have a DatetimeIndex.")

    out = df.copy()
    out.index = pd.to_datetime(out.index)

    if assume_local_tz is not None and out.index.tz is not None:
        out.index = out.index.tz_convert(assume_local_tz).tz_localize(None)

    out = out.sort_index()
    out = _dedup_index(out, duplicate_policy)

    if round_freq is not None:
        rounded_index = out.index.round(round_freq)
        out = out.groupby(rounded_index).last()
        out.index.name = df.index.name
        out = _dedup_index(out, duplicate_policy)

    return out


