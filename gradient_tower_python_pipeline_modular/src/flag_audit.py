def _infer_samples_per_hour(index: pd.DatetimeIndex) -> int:
    """Infer nominal samples per hour from the DatetimeIndex.

    Falls back to 60 if inference is not possible.
    """
    if len(index) < 2:
        return 60

    # Cambiado a .asi8 para evitar advertencias de desuso de view("int64") en Pandas recientes
    dt_sec = np.diff(index.asi8) / 1e9
    dt_sec = dt_sec[np.isfinite(dt_sec)]
    dt_sec = dt_sec[dt_sec > 0]

    if len(dt_sec) == 0:
        return 60

    step_sec = int(round(np.median(dt_sec)))
    if step_sec <= 0:
        return 60

    return max(1, int(round(3600 / step_sec)))


def audit_data_availability(df: pd.DataFrame, cfg: TowerConfig, threshold: float = 0.8) -> pd.DataFrame:
    """Realiza una auditoría de disponibilidad horaria y devuelve un DataFrame con los resultados."""
    if not isinstance(df.index, pd.DatetimeIndex):
        raise ValueError("El DataFrame debe tener un DatetimeIndex.")

    samples_per_hour = _infer_samples_per_hour(df.index)
    
    # Lógica de temporadas unificada (Sincronizada con el resto del pipeline)
    is_dry = df.index.month.isin([5, 6, 7, 8, 9])
    
    epochs = [
        (df.loc[is_dry], "Seca (May-Sep)"),
        (df.loc[~is_dry], "Lluviosa (Oct-Apr)")
    ]
    
    # Construcción segura de mapeos dinámicos desde la configuración de la torre
    all_mappings = {}
    for attr in ["temp_cols", "rh_cols", "wind_cols", "wdir_cols"]:
        mapping = getattr(cfg, attr, {})
        if mapping:
            all_mappings.update(mapping)
    
    print(f"\n{'='*70}")
    print(f"AUDITORÍA DE DISPONIBILIDAD HORARIA (Umbral: {threshold*100:.0f}%)")
    print(f"{'='*70}")

    all_results = []

    for data_epoch, title_epoch in epochs:
        if data_epoch.empty:
            continue
            
        n_days = data_epoch.index.normalize().nunique()
        expected_per_hour = max(1, n_days * samples_per_hour)
        
        epoch_results = []
        for height, col_name in all_mappings.items():
            if col_name not in data_epoch.columns:
                continue
            
            # Agrupación explícita por hora cronológica del índice
            counts = data_epoch[col_name].groupby(data_epoch.index.hour).count()
            counts = counts.reindex(range(24), fill_value=0)
            
            # Identificación de horas con pérdida crítica de datos
            hours_discarded = counts[counts / expected_per_hour < threshold].index.tolist()
            
            epoch_results.append({
                "Temporada": title_epoch,
                "Días_Evaluados": n_days,
                "Sensor": col_name,
                "Altura": f"{height}m",
                "Estado": "✅ OK" if not hours_discarded else f"⚠️ {len(hours_discarded)}h DESCARTADAS",
                "Horas_Afectadas": str(hours_discarded) if hours_discarded else "-"
            })
        
        audit_df = pd.DataFrame(epoch_results)
        print(f"\n>>> Estación: {title_epoch} ({n_days} días)")
        if not audit_df.empty:
            print(audit_df.drop(columns=["Temporada", "Días_Evaluados"]).to_string(index=False))
        
        all_results.extend(epoch_results)
            
    print(f"{'='*70}\n")
    
    return pd.DataFrame(all_results)


def _hourly_stats_linear(df: pd.DataFrame, cols: List[str]) -> Dict[str, pd.DataFrame]:
    """Compute hourly mean, std, count for linear physical variables."""
    out = {}
    for col in cols:
        if col not in df.columns:
            continue

        s = pd.to_numeric(df[col], errors="coerce")
        grp = s.groupby(df["hour"])
        stats = grp.agg(["mean", "std", "count"]).reindex(range(24))
        out[col] = stats

    return out


def _circular_mean_deg(series: pd.Series) -> float:
    """Circular mean implementation in degrees using vector native NumPy operations."""
    x = pd.to_numeric(series, errors="coerce").dropna().values
    if x.size == 0:
        return np.nan

    rad = np.deg2rad(x % 360.0)
    s = np.sin(rad).mean()
    c = np.cos(rad).mean()

    if np.isclose(s, 0.0) and np.isclose(c, 0.0):
        return np.nan

    return float(np.rad2deg(np.arctan2(s, c)) % 360.0)


def _circular_std_deg(series: pd.Series) -> float:
    """Circular standard deviation in degrees optimized for multi-level datasets."""
    x = pd.to_numeric(series, errors="coerce").dropna().values
    if x.size == 0:
        return np.nan

    rad = np.deg2rad(x % 360.0)
    s = np.sin(rad).mean()
    c = np.cos(rad).mean()
    R = np.sqrt(s**2 + c**2)

    if R <= 0 or R >= 1.0:
        return np.nan

    circ_std_rad = np.sqrt(-2.0 * np.log(R))
    return float(np.rad2deg(circ_std_rad))


def _hourly_stats_circular(df: pd.DataFrame, cols: List[str]) -> Dict[str, pd.DataFrame]:
    """Compute hourly circular mean, circular std, and valid count for angular variables."""
    out = {}
    for col in cols:
        if col not in df.columns:
            continue

        rows = []
        for hour in range(24):
            s = pd.to_numeric(df.loc[df["hour"] == hour, col], errors="coerce").dropna()

            if s.empty:
                rows.append({"mean": np.nan, "std": np.nan, "count": 0})
            else:
                rows.append({
                    "mean": _circular_mean_deg(s),
                    "std": _circular_std_deg(s),
                    "count": int(s.count())
                })

        out[col] = pd.DataFrame(rows, index=range(24))

    return out


def plot_diurnal_science_ready_with_wdir(
    df: pd.DataFrame,
    cfg: TowerConfig,
    threshold: float = 0.8,
    save_path: str = "figures_qc/diurnal_cycle_validated_with_wdir.png"
) -> None:
    """Generates a publication-quality diurnal cycle plot split by meteorological seasons.

    Fully unifies tracking for both linear variables and wind direction coordinates.
    """
    if not isinstance(df.index, pd.DatetimeIndex):
        raise ValueError("df must have a DatetimeIndex.")

    if not (0 < threshold <= 1):
        raise ValueError("threshold must be in the interval (0, 1].")

    # 1) Preparación de estructuras y aislamiento de columnas configuradas
    df_copy = df.copy().sort_index()

    temp_cols = [c for c in getattr(cfg, "temp_cols", {}).values() if c in df_copy.columns]
    rh_cols = [c for c in getattr(cfg, "rh_cols", {}).values() if c in df_copy.columns]
    wind_cols = [c for c in getattr(cfg, "wind_cols", {}).values() if c in df_copy.columns]
    wdir_cols = [c for c in getattr(cfg, "wdir_cols", {}).values() if c in df_copy.columns]

    cols_to_use = temp_cols + rh_cols + wind_cols + wdir_cols
    if not cols_to_use:
        raise ValueError("Ninguna de las columnas configuradas en la Torre fue hallada en el DataFrame.")

    df_copy = df_copy[cols_to_use].copy()
    df_copy["hour"] = df_copy.index.hour
    df_copy["date"] = df_copy.index.normalize()

    # Separación consistente de la serie por épocas climáticas (Seca vs Lluviosa)
    is_dry = df_copy.index.month.isin([5, 6, 7, 8, 9])
    
    epochs = [
        (df_copy.loc[is_dry], "Dry Season (May-Sep)"),
        (df_copy.loc[~is_dry], "Wet Season (Oct-Apr)")
    ]

    # 2) Configuración del Lienzo Científico (Matplotlib Context)
    with plt.rc_context({
        "font.size": 20,
        "axes.titlesize": 20,
        "axes.labelsize": 20,
        "xtick.labelsize": 20,
        "ytick.labelsize": 20
    }):
        var_groups = [
            (getattr(cfg, "temp_cols", {}), "Temperature (°C)", "linear"),
            (getattr(cfg, "rh_cols", {}), "Relative Humidity (%)", "linear"),
            (getattr(cfg, "wind_cols", {}), "Wind Speed (m/s)", "linear"),
            (getattr(cfg, "wdir_cols", {}), "Wind Direction (°)", "circular"),
        ]

        # Limpieza de subplots vacíos si alguna variable no cuenta con mapeo activo
        var_groups = [vg for vg in var_groups if vg[0]]
        n_rows = len(var_groups)

        fig, axes = plt.subplots(n_rows, 2, figsize=(16, 4 * n_rows), sharex=True, sharey="row")
        
        if n_rows == 1:
            axes = axes[np.newaxis, :]

        # Paleta de colores profesionales con alto contraste visual
        colors = ["#4477AA", "#66CCEE", "#CCBB44", "#EE6677", "#228833", "#AA3377"]
        markers = ["o", "s", "^", "D", "v", "P"]

        samples_per_hour = _infer_samples_per_hour(df_copy.index)

        # 3) Procesamiento Estadístico Avanzado y Graficación por Época
        for col_idx, (data_epoch, title_epoch) in enumerate(epochs):
            if data_epoch.empty:
                continue

            n_days = data_epoch["date"].nunique()
            expected_per_hour = max(1, n_days * samples_per_hour)

            l_cols = [c for c in temp_cols + rh_cols + wind_cols if c in data_epoch.columns]
            c_cols = [c for c in wdir_cols if c in data_epoch.columns]

            hourly_stats_linear = _hourly_stats_linear(data_epoch, l_cols)
            hourly_stats_circular = _hourly_stats_circular(data_epoch, c_cols)

            for row_idx, (mapping, ylabel, vtype) in enumerate(var_groups):
                ax = axes[row_idx, col_idx]

                for i, (height, col_name) in enumerate(mapping.items()):
                    if col_name not in data_epoch.columns:
                        continue

                    stats = hourly_stats_circular.get(col_name) if vtype == "circular" else hourly_stats_linear.get(col_name)
                    if stats is None:
                        continue

                    # Filtro estricto de disponibilidad mínima por hora cronológica
                    mask = (stats["count"] / expected_per_hour) >= threshold
                    m = stats["mean"].where(mask)
                    s = stats["std"].where(mask)
                    hours = stats.index.to_numpy()

                    color = colors[i % len(colors)]
                    marker = markers[i % len(markers)]

                    # Traza de la curva promedio principal
                    ax.plot(
                        hours, m.to_numpy(dtype=float),
                        label=f"{height} m", color=color, marker=marker,
                        markersize=5, lw=1.8, zorder=3
                    )

                    # Banda sombreada de variabilidad física (Desviación Estándar)
                    ax.fill_between(
                        hours, 
                        (m - s).to_numpy(dtype=float), 
                        (m + s).to_numpy(dtype=float),
                        color=color, alpha=0.10, zorder=2
                    )

                    # Anotación científica automática de extremos locales (Máximos y Mínimos)
                    valid_m = m.dropna()
                    if not valid_m.empty:
                        idx_max, val_max = valid_m.idxmax(), valid_m.max()
                        idx_min, val_min = valid_m.idxmin(), valid_m.min()

                        for idx, val, offset, va in [(idx_max, val_max, 7, "bottom"), (idx_min, val_min, -7, "top")]:
                            ax.scatter([idx], [val], color=color, s=20, zorder=5, edgecolor="black", linewidth=0.4)
                            ax.annotate(
                                f"{val:.1f}", xy=(idx, val), xytext=(0, offset),
                                textcoords="offset points", ha="center", va=va,
                                fontsize=8, color=color, fontweight="bold", zorder=6
                            )

                # Formateo técnico de rejillas y etiquetas de ejes
                if row_idx == 0:
                    ax.set_title(f"{title_epoch} ({n_days} days)", fontweight="bold", pad=12)
                if col_idx == 0:
                    ax.set_ylabel(ylabel, fontweight="bold", labelpad=8)
                
                # Ajustes fijos de límites físicos lógicos
                if "Humidity" in ylabel:
                    ax.set_ylim(-5, 105)
                elif "Wind Direction" in ylabel:
                    ax.set_ylim(-10, 370)
                    ax.set_yticks(np.arange(0, 361, 90))

                ax.grid(True, linestyle=":", alpha=0.5)
                ax.text(
                        0.02, 0.04, fr"Avail $\geq$ {threshold*100:.0f}%",  # <--- Añadida la 'r' para hacerla Raw String
                        transform=ax.transAxes, ha="left", va="bottom", fontsize=15, alpha=0.5,
                        bbox=dict(facecolor='white', alpha=0.6, edgecolor='none', pad=1)
                        )

        # Configuración final del eje temporal (X)
        for ax in axes[-1, :]:
            ax.set_xlabel("Local Time (Hour)", fontweight="bold", labelpad=8)
            ax.set_xticks(range(0, 24, 2))
            ax.set_xlim(-0.5, 23.5)

        # Extracción limpia de la leyenda para evitar duplicación entre paneles
        handles, labels = None, None
        for ax in fig.axes:
            h, l = ax.get_legend_handles_labels()
            if h:
                handles, labels = h, l
                break

        if handles:
            fig.legend(
                handles, labels, loc="lower center", bbox_to_anchor=(0.5, -0.01),
                ncol=max(1, len(labels)), title="Sensor Height AGL (meters)",
                frameon=False, fontsize=20, title_fontsize=20
            )

        # Ajuste de márgenes para prevenir superposición de textos científicos
        fig.tight_layout(rect=[0, 0.05, 1, 1], h_pad=1.0, w_pad=1.0)

        # Almacenamiento seguro en disco
        save_dir = os.path.dirname(save_path)
        if save_dir:
            os.makedirs(save_dir, exist_ok=True)

        plt.savefig(save_path, bbox_inches="tight", dpi=600)
        plt.show()


