def save_30min_statistics_to_netcdf(
    cleaned_df: pd.DataFrame,
    output_nc: str,
    cfg: Optional[TowerConfig] = None,
    period: str = "30min",
    timezone_local: str = "America/Lima",
    store_time_as_utc: bool = True,
    global_attrs: Optional[Dict[str, Any]] = None,
) -> xr.Dataset:
    """Time-aggregates high-frequency climate tower data into a robust NetCDF data structure."""
    if not isinstance(cleaned_df.index, pd.DatetimeIndex):
        raise ValueError("cleaned_df debe tener un DatetimeIndex válido.")
    if cleaned_df.empty:
        raise ValueError("El DataFrame cleaned_df está vacío.")
    if pd.Timedelta(period).total_seconds() <= 0:
        raise ValueError("El parámetro period debe reflejar una frecuencia válida positiva.")

    df = cleaned_df.copy().sort_index()

    # 1. Conversión forzada y segura a tipos de datos numéricos flotantes
    numeric_df = pd.DataFrame(index=df.index)
    for col in df.columns:
        numeric_df[col] = pd.to_numeric(df[col], errors="coerce")

    cols_to_process = [col for col in numeric_df.columns if numeric_df[col].notna().any()]
    if not cols_to_process:
        raise ValueError("No se encontraron variables con registros numéricos válidos para procesar.")

    numeric_df = numeric_df[cols_to_process]
    wdir_cols = detect_wind_direction_columns(numeric_df, cfg=cfg)
    expected_samples = infer_samples_per_period(numeric_df.index, period=period)

    # 2. Resampling temporal estructurado de matrices estadísticas
    resampler = numeric_df.resample(period)
    
    # Inicialización acelerada de estructuras vacías con índices temporales correctos
    resample_index = resampler.mean().index
    mean_df = pd.DataFrame(index=resample_index)
    std_df = pd.DataFrame(index=resample_index)
    min_df = pd.DataFrame(index=resample_index)
    max_df = pd.DataFrame(index=resample_index)
    count_df = pd.DataFrame(index=resample_index)

    for col in cols_to_process:
        s = numeric_df[col]
        col_resampler = s.resample(period)

        if col in wdir_cols:
            # Vinculación metodológica con las funciones matemáticas optimizadas de NumPy (Bloque 3)
            mean_df[col] = col_resampler.apply(_circular_mean_deg)
            std_df[col] = col_resampler.apply(_circular_std_deg)
            # Los extremos angulares se manejan de manera lineal diagnóstica bajo advertencia de metadato
            min_df[col] = col_resampler.min()
            max_df[col] = col_resampler.max()
        else:
            mean_df[col] = col_resampler.mean()
            std_df[col] = col_resampler.std()
            min_df[col] = col_resampler.min()
            max_df[col] = col_resampler.max()
            
        count_df[col] = col_resampler.count()

    expected_df = pd.DataFrame(expected_samples, index=resample_index, columns=cols_to_process)
    availability_df = (100.0 * count_df / expected_df).clip(lower=0.0, upper=100.0)

    # 3. Alineación e internacionalización del eje temporal de coordenadas
    time_index = resample_index
    if store_time_as_utc:
        if time_index.tz is None:
            time_coord = time_index.tz_localize(timezone_local).tz_convert("UTC").tz_localize(None)
        else:
            time_coord = time_index.tz_convert("UTC").tz_localize(None)
            
        time_attrs = {
            "standard_name": "time",
            "axis": "T",
            "long_name": f"Start time of each {period} aggregation interval in UTC",
            "timezone_original": timezone_local,
            "timezone_stored": "UTC",
        }
    else:
        time_coord = time_index.tz_localize(None) if time_index.tz is not None else time_index
        time_attrs = {
            "standard_name": "time",
            "axis": "T",
            "long_name": f"Start time of each {period} aggregation interval in local time",
            "timezone_stored": timezone_local,
        }

    # 4. Construcción del objeto integrado xarray Dataset
    ds_out = xr.Dataset(
        coords={
            "time": xr.DataArray(time_coord, dims=("time",), attrs=time_attrs)
        }
    )

    statistic_tables = {
        "mean": mean_df,
        "std": std_df,
        "min": min_df,
        "max": max_df,
        "valid_count": count_df,
        "expected_count": expected_df,
        "availability_pct": availability_df,
    }

    # 5. Volcado e inyección de variables físicas y capas de diagnóstico
    for col in cols_to_process:
        safe_col = sanitize_netcdf_name(col)
        units = get_variable_units(col)
        long_name = get_variable_long_name(col)
        is_wdir = col in wdir_cols

        for stat_name, table in statistic_tables.items():
            var_name = f"{safe_col}_{stat_name}"

            if stat_name in ["valid_count", "expected_count"]:
                values = table[col].to_numpy(dtype=np.int32)
                stat_units = "1"
            elif stat_name == "availability_pct":
                values = table[col].to_numpy(dtype=float)
                stat_units = "%"
            else:
                values = table[col].to_numpy(dtype=float)
                stat_units = units

            # Generación de trazabilidad procedimental de metadatos (Provenance mapping)
            if stat_name == "mean":
                method = "circular mean" if is_wdir else "arithmetic mean"
            elif stat_name == "std":
                method = "circular standard deviation" if is_wdir else "sample standard deviation"
            elif stat_name in ["min", "max"] and is_wdir:
                method = "linear observed angular extremum; diagnostic only for circular data"
            elif stat_name == "availability_pct":
                method = "100 * valid_count / expected_count"
            else:
                method = stat_name

            ds_out[var_name] = xr.DataArray(
                values,
                dims=("time",),
                coords={"time": ds_out["time"]},
                attrs={
                    "units": stat_units,
                    "long_name": f"{period} {stat_name} of {long_name}",
                    "aggregation_period": period,
                    "original_variable": str(col),
                    "statistic": stat_name,
                    "method": method,
                }
            )

    # 6. Atributos globales del archivo (Estándares Internacionales COARDS/CF)
    ds_out.attrs.update({
        "title": f"{period} Statistics from Cleaned Meteorological Tower Data",
        "summary": (
            f"This NetCDF file contains {period} mean, standard deviation, "
            f"minimum, maximum, valid sample count, expected sample count, and "
            f"availability percentage for each numeric variable in the cleaned "
            f"meteorological tower dataset."
        ),
        "institution": "Instituto Geofísico del Perú (IGP)",
        "source_dataframe": "cleaned_from_nc",
        "processing_level": "Aggregated statistics from quality-controlled data",
        "aggregation_period": period,
        "expected_samples_per_period": int(expected_samples),
        "availability_percentage_definition": "100 * valid_count / expected_count",
        "linear_statistics": "Arithmetic mean, sample standard deviation, minimum, and maximum",
        "circular_statistics": (
            "Circular mean and circular standard deviation were used for wind "
            "direction variables. Minimum and maximum wind direction values are "
            "stored as linear observed extrema and should be interpreted cautiously."
        ),
        "wind_direction_columns": ", ".join(wdir_cols) if wdir_cols else "None detected",
        "time_interval_label": "left",
        "time_interval_closed": "left",
        # CORREGIDO: Uso del estándar moderno de zona horaria explícita para evitar DeprecationWarnings
        "created": f"{datetime.now(timezone.utc).isoformat().replace('+00:00', 'Z')}",
        "Conventions": "CF-1.8",
    })

    if global_attrs:
        ds_out.attrs.update(global_attrs)

    # 7. Configuración de codecs de compresión y guardado físico en disco
    output_dir = os.path.dirname(output_nc)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    encoding = {
        var: {"zlib": True, "complevel": 4} for var in ds_out.data_vars
    }
    encoding["time"] = {
        "units": "seconds since 1970-01-01 00:00:00",
        "calendar": "proleptic_gregorian",
        "dtype": "int64",
    }

    ds_out.to_netcdf(
        output_nc,
        format="NETCDF4",
        engine="netcdf4",
        mode="w",
        encoding=encoding,
    )

    print(f"NetCDF guardado exitosamente en: {output_nc}")
    print(f"Número de variables finales procesadas: {len(ds_out.data_vars)}")
    return ds_out


