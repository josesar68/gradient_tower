def validate_tower_config_integrity(cfg: TowerConfig) -> pd.DataFrame:
    """Returns a detailed report in Pandas evaluating global collisions of column names.

    Modified to detect if the same column name was erroneously assigned to different variables.
    """
    rows = []
    mappings = {
        "temp_cols": cfg.temp_cols,
        "rh_cols": cfg.rh_cols,
        "wind_cols": cfg.wind_cols,
        "wdir_cols": cfg.wdir_cols,
    }
    
    # Global list to track if a physical column is assigned to two different sensors simultaneously
    all_assigned_cols = []
    for mapping in mappings.values():
        all_assigned_cols.extend(list(mapping.values()))

    for name, mapping in mappings.items():
        cols = list(mapping.values())
        
        # 1. Internal duplicates within the same dictionary
        internal_dups = sorted({c for c in cols if cols.count(c) > 1})
        
        # 2. Cross-variable collisions in the tower
        cross_collisions = sorted({c for c in cols if all_assigned_cols.count(c) > cols.count(c)})
        
        # Status of the analyzed row
        has_issues = bool(internal_dups or cross_collisions)
        
        rows.append({
            "mapping": name,
            "n_columns": len(cols),
            "duplicated_internal_names": ", ".join(internal_dups) if internal_dups else "Ninguno",
            "cross_variable_collisions": ", ".join(cross_collisions) if cross_collisions else "Ninguna",
            "status": "REVIEW" if has_issues else "OK",
        })
        
    return pd.DataFrame(rows)


