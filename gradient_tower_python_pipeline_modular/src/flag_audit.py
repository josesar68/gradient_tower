def plot_seasonal_vertical_profiles_publication(
    df: pd.DataFrame, 
    cfg: TowerConfig, 
    save_prefix: str = "figures_qc/seasonal_profile"
) -> None:
    """Generates multi-level vertical profiles of thermodynamics variables

    Uses a layout optimized for high-impact scientific journals.
    """
    if df.empty:
        raise ValueError("El DataFrame de entrada está vacío.")

    # 1. Definición unificada de temporadas climáticas
    month_array = df.index.month
    is_dry = (month_array >= 5) & (month_array <= 9)
    seasons = [(df.loc[is_dry], "Dry Season"), (df.loc[~is_dry], "Wet Season")]

    heights = cfg.heights_m
    
    # Estructura del Layout (Título, Símbolo LaTeX, Diccionario Config, Unidades, Factor Escala)
    plot_config = [
        ("Temperature", r"$T$", cfg.temp_cols, r"^\circ\mathrm{C}", 1.0), 
        ("Virtual Potential Temperature", r"$\theta_v$", "theta_v", r"\mathrm{K}", 1.0),
        ("Specific Humidity", r"$q$", "q", r"10^{-3} \, \mathrm{kg} \, \mathrm{kg}^{-1}", 1000.0)
    ]

    hours_to_plot = [0, 4, 8, 12, 16, 20]
    
    for df_season, season_name in seasons:
        if df_season.empty: 
            continue
            
        hourly_means = df_season.groupby(df_season.index.hour).mean(numeric_only=True)

        fig, axes = plt.subplots(3, 1, figsize=(10, 13), constrained_layout=True)
        
        cmap = plt.get_cmap("inferno")
        colors = [cmap((i / 24) * 0.8 + 0.1) for i in hours_to_plot]

        for ax, (title, symbol, col_source, units, scale) in zip(axes, plot_config):
            all_vals = [] 
            
            for hr, color in zip(hours_to_plot, colors):
                if hr not in hourly_means.index: 
                    continue
                
                vals, v_heights = [], []
                for h in heights:
                    # Selección e identificación segura del nombre de columna según el Bloque de Configuración
                    if isinstance(col_source, dict):
                        col_name = col_source.get(h)
                    else:
                        # Para variables derivadas generadas con sufijo de altura estandarizado (q, theta_v)
                        suffix = str(int(h)) if float(h).is_integer() else str(h).replace(".", "p")
                        col_name = f"{col_source}_{suffix}"
                    
                    if col_name and col_name in hourly_means.columns:
                        val = hourly_means.loc[hr, col_name]
                        if pd.notna(val):
                            vals.append(val * scale)
                            v_heights.append(h)
                
                if vals:
                    all_vals.extend(vals)
                    ax.plot(vals, v_heights, marker='o', lw=1.8, color=color, 
                            markersize=6, label=f"{hr:02d}:00", zorder=3)
                    
                    # Anotación horaria refinada en formato Raw String para LaTeX seguro
                    ax.text(vals[-1], v_heights[-1] + 0.6, fr"$\mathbf{{{hr:02d}h}}$", 
                            color=color, ha='center', fontsize=9)

            # Estilo técnico de los ejes del panel
            ax.set_title(title, loc='left', fontsize=12, fontweight='bold')
            ax.set_xlabel(fr"{symbol} $({units})$", fontsize=15)
            ax.set_ylabel(r"Height $(\mathrm{m \, AGL})$", fontsize=15)
            
            ax.set_ylim(0, max(heights) + 5)
            ax.set_yticks(heights)
            
            ax.tick_params(axis='both', which='major', labelsize=15, length=5, width=1.0)
            ax.xaxis.set_major_formatter(FormatStrFormatter('%.1f'))

            if all_vals:
                vmin, vmax = min(all_vals), max(all_vals)
                pad = (vmax - vmin) * 0.15 if vmax != vmin else 1.0
                ax.set_xlim(vmin - pad, vmax + pad)

        fig.suptitle(f"Vertical Profiles: {season_name}", fontsize=15, fontweight='bold', y=1.01)
        
        save_dir = os.path.dirname(save_prefix)
        if save_dir: 
            os.makedirs(save_dir, exist_ok=True)
            
        clean_name = season_name.lower().replace(" ", "_")
        plt.savefig(f"{save_prefix}_{clean_name}.png", dpi=600, bbox_inches="tight")
        plt.show()


def plot_seasonal_wind_profiles_publication(
    df: pd.DataFrame, 
    cfg: TowerConfig, 
    save_prefix: str = "figures_qc/seasonal_wind"
) -> None:
    """Generates vertical profiles for wind speed and robust diurnal circular stats for wind direction."""
    if df.empty:
        return

    month_array = df.index.month
    is_dry = (month_array >= 5) & (month_array <= 9)
    seasons = [(df.loc[is_dry], "Dry Season"), (df.loc[~is_dry], "Wet Season")]

    heights = cfg.heights_m
    hours_to_plot = [0, 4, 8, 12, 16, 20]
    
    # Extraer de manera segura la columna de dirección de viento (usualmente a 24m)
    wdir_col = next(iter(cfg.wdir_cols.values()), None)
    
    for df_season, season_name in seasons:
        if df_season.empty: 
            continue
        
        # --- PROCESAMIENTO KINEMÁTICO AVANZADO ---
        # Separación y cálculo lineal para velocidad
        df_copy = df_season.copy()
        df_copy["hour"] = df_copy.index.hour
        
        ws_cols = [c for c in cfg.wind_cols.values() if c in df_copy.columns]
        hourly_ws_means = df_copy.groupby("hour")[ws_cols].mean()

        # Corrección metodológica: Estadísticas de dirección usando funciones circulares del Bloque 3
        stats_circular_wd = {}
        if wdir_col and wdir_col in df_copy.columns:
            for hr in range(24):
                subset = df_copy.loc[df_copy["hour"] == hr, wdir_col].dropna()
                stats_circular_wd[hr] = {
                    "mean": _circular_mean_deg(subset),
                    "std": _circular_std_deg(subset)
                }

        fig = plt.figure(figsize=(10, 13), constrained_layout=True)
        gs = fig.add_gridspec(2, 1, height_ratios=[1.3, 1])
