def extract_2d_variable_to_original_columns(
    ds: xr.Dataset,
    var_name: str,
    col_map: Dict[float, str],
) -> pd.DataFrame:
    """Extract a 2-D variable with dimensions (time, height) into original tower columns.

    Optimized to bypass redundant pandas transformations inside loops using direct NumPy arrays.
    """
    time_index = pd.to_datetime(ds["time"].values)

    if var_name not in ds:
        return pd.DataFrame(index=time_index)

    da = ds[var_name]

    if not {"time", "height"}.issubset(set(da.dims)):
        raise ValueError(f"Variable {var_name!r} must have dimensions ('time', 'height'). Found: {da.dims}")

    if "height" not in da.coords:
        raise ValueError(f"Variable {var_name!r} has a height dimension but no height coordinate.")

    out = pd.DataFrame(index=time_index)
    available_heights = np.asarray(da["height"].values, dtype=float)

    for height, original_col in col_map.items():
        if np.any(np.isclose(available_heights, height)):
            # Find the closest numerical index
            idx = np.argmin(np.abs(available_heights - height))
            # Optimization: Direct extraction using slicing of native vectors (.values)
            out[original_col] = da.isel(height=idx).values

    out.index.name = "time"
    return out


def extract_derived_variables(ds: xr.Dataset, var_name: str) -> pd.DataFrame:
    """Extract derived time-height variables such as q and theta_v directly to NumPy."""
    time_index = pd.to_datetime(ds["time"].values)

    if var_name not in ds:
        return pd.DataFrame(index=time_index)

    da = ds[var_name]

    if not {"time", "height"}.issubset(set(da.dims)):
        raise ValueError(f"Variable {var_name!r} must have dimensions ('time', 'height'). Found: {da.dims}")

    out = pd.DataFrame(index=time_index)

    for idx, height in enumerate(np.asarray(da["height"].values, dtype=float)):
        suffix = str(int(height)) if float(height).is_integer() else str(height).replace(".", "p")
        # Optimization: Direct access using native position index without Pandas overhead
        out[f"{var_name}_{suffix}"] = da.isel(height=idx).values

    out.index.name = "time"
    return out


def extract_qc_flags_to_original_columns(
    ds: xr.Dataset,
    qc_var_name: str,
    col_map: Dict[float, str],
    fill_missing_flag: int = BIT_MISSING,
) -> pd.DataFrame:
    """Extract QC flags with original tower column names, avoiding global dict lookups."""
    df = extract_2d_variable_to_original_columns(ds, qc_var_name, col_map)

    for col in df.columns:
# Empty or NaN flags are forced to the corresponding missing (MISSING) bitmask
        df[col] = pd.to_numeric(df[col], errors="coerce").fillna(fill_missing_flag).astype("int32")

    return df


def _concat_or_empty(parts: List[pd.DataFrame], index: pd.DatetimeIndex) -> pd.DataFrame:
    valid = [df for df in parts if df is not None and not df.empty]
    if valid:
        return pd.concat(valid, axis=1)
    return pd.DataFrame(index=index)


def read_saved_tower_dataframes_from_netcdf(
    nc_file: str,
    convert_to_local: Optional[bool] = None,
    local_tz: str = "America/Lima",
    remove_timezone: bool = True,
    engine: str = "netcdf4",
    **legacy_kwargs: Any,
) -> Tuple[pd.DataFrame, pd.DataFrame, Optional[pd.DataFrame], xr.Dataset, Optional[xr.Dataset]]:
    """Read cleaned, QC flags and raw-uncontrolled DataFrames from the OGHYO tower NetCDF file."""
    if convert_to_local is None:
        convert_to_local = bool(legacy_kwargs.pop("convert_to_lima", True))
    elif "convert_to_lima" in legacy_kwargs:
        warnings.warn("Both convert_to_local and convert_to_lima were supplied; using convert_to_local.")
        legacy_kwargs.pop("convert_to_lima")

    if legacy_kwargs:
        raise TypeError(f"Unexpected keyword argument(s): {list(legacy_kwargs)}")

    if not os.path.exists(nc_file):
        raise FileNotFoundError(f"NetCDF file does not exist: {os.path.abspath(nc_file)}")

    # 1. Carga de dataset principal de variables procesadas
    ds = xr.open_dataset(nc_file, engine=engine, decode_times=True)
    time_index = pd.to_datetime(ds["time"].values)

    # 2. Carga segura del grupo "raw_uncontrolled"
    try:
        ds_raw = xr.open_dataset(nc_file, group="raw_uncontrolled", engine=engine, decode_times=True)
    except Exception as exc:
        warnings.warn(f"Could not open NetCDF group 'raw_uncontrolled': {exc}")
        ds_raw = None

    # 3. Procesamiento y reconstrucción de variables limpias y derivadas
    cleaned_parts = [
        extract_2d_variable_to_original_columns(ds, "ta", TEMP_COLS),
        extract_2d_variable_to_original_columns(ds, "hur", RH_COLS),
        extract_2d_variable_to_original_columns(ds, "ws", WIND_COLS),
        extract_2d_variable_to_original_columns(ds, "wd", WDIR_COLS),
        extract_derived_variables(ds, "q"),
        extract_derived_variables(ds, "theta_v"),
    ]
    cleaned_from_nc = _concat_or_empty(cleaned_parts, index=time_index)

    if "P_Pa" in ds:
        # Optimización: Extracción directa sin instanciar dataframe intermedio de Pandas
        cleaned_from_nc["P_Pa"] = ds["P_Pa"].values

    # 4. Procesamiento de banderas de control de calidad
    flag_parts = [
        extract_qc_flags_to_original_columns(ds, "ta_qc_flags", TEMP_COLS),
        extract_qc_flags_to_original_columns(ds, "hur_qc_flags", RH_COLS),
        extract_qc_flags_to_original_columns(ds, "ws_qc_flags", WIND_COLS),
        extract_qc_flags_to_original_columns(ds, "wd_qc_flags", WDIR_COLS),
    ]
    flags_from_nc = _concat_or_empty(flag_parts, index=time_index)

    # 5. Tratamiento consistente del grupo crudo (Desarticulación limpia de MultiIndex de alturas)
    if ds_raw is not None:
        if "height" in ds_raw.dims:
            # Si tiene altura como dimensión, se unifica de manera idéntica al dataset limpio
            raw_parts = [
                extract_2d_variable_to_original_columns(ds_raw, "ta", TEMP_COLS),
                extract_2d_variable_to_original_columns(ds_raw, "hur", RH_COLS),
                extract_2d_variable_to_original_columns(ds_raw, "ws", WIND_COLS),
                extract_2d_variable_to_original_columns(ds_raw, "wd", WDIR_COLS),
            ]
            raw_from_nc = _concat_or_empty(raw_parts, index=time_index)
        else:
            # Si es un dataset plano unidimensional (sólo tiempo)
            raw_from_nc = ds_raw.to_dataframe().dropna(axis=1, how="all")
            if isinstance(raw_from_nc.index, pd.MultiIndex):
                if "time" not in raw_from_nc.index.names:
                    raise ValueError("raw_uncontrolled group has a MultiIndex without a 'time' level.")
                raw_from_nc = raw_from_nc.reset_index().set_index("time")
            raw_from_nc.index = pd.to_datetime(raw_from_nc.index)
            raw_from_nc.index.name = "time"
    else:
        raw_from_nc = None

    # 6. Conversión horaria centralizada y segura
    if convert_to_local:
        cleaned_from_nc = convert_index_utc_to_local(cleaned_from_nc, local_tz=local_tz, remove_timezone=remove_timezone)
        flags_from_nc = convert_index_utc_to_local(flags_from_nc, local_tz=local_tz, remove_timezone=remove_timezone)
        if raw_from_nc is not None:
            raw_from_nc = convert_index_utc_to_local(raw_from_nc, local_tz=local_tz, remove_timezone=remove_timezone)

    return cleaned_from_nc, flags_from_nc, raw_from_nc, ds, ds_raw


