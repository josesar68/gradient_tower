def sanitize_netcdf_variable_name(name: str) -> str:
    """
    Make a pandas column name safer for NetCDF variable naming.

    NetCDF variable names should avoid spaces, parentheses, slashes and special
    characters. This function keeps names readable and reproducible.
    """

    new = str(name).strip()

    replacements = {
        " ": "_",
        "(": "",
        ")": "",
        "[": "",
        "]": "",
        "{": "",
        "}": "",
        "/": "_per_",
        "\\": "_",
        "-": "_",
        ":": "_",
        ";": "_",
        ",": "_",
        ".": "_",
        "%": "pct",
        "*": "star",
    }

    for old, new_char in replacements.items():
        new = new.replace(old, new_char)

    while "__" in new:
        new = new.replace("__", "_")

    new = new.strip("_")

    if not new:
        new = "unnamed_variable"

    if new[0].isdigit():
        new = f"var_{new}"

    return new


def sanitize_dataframe_columns_for_netcdf(
    df: pd.DataFrame,
) -> Tuple[pd.DataFrame, Dict[str, str]]:
    """
    Rename DataFrame columns to NetCDF-safe names.

    Returns
    -------
    df_out : pd.DataFrame
        DataFrame with sanitized column names.
    name_map : dict
        Mapping from original column name to sanitized column name.
    """

    used = set()
    name_map: Dict[str, str] = {}

    for original in df.columns:
        base = sanitize_netcdf_variable_name(original)
        candidate = base
        counter = 2

        while candidate in used:
            candidate = f"{base}_{counter}"
            counter += 1

        used.add(candidate)
        name_map[str(original)] = candidate

    df_out = df.rename(columns=name_map).copy()

    return df_out, name_map

