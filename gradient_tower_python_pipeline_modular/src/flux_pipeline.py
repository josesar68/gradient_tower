def infer_expected_samples_per_period(index: pd.DatetimeIndex, freq: str) -> int:
    """Infer expected sample count per aggregation period from a regular index."""
    if len(index) < 2:
        return 1
    inferred = pd.infer_freq(index)
    if inferred is not None:
        base_delta = pd.to_timedelta(pd.tseries.frequencies.to_offset(inferred))
    else:
        diffs = index.to_series().diff().dropna()
        if diffs.empty:
            return 1
        base_delta = diffs.median()
    period_delta = pd.to_timedelta(pd.tseries.frequencies.to_offset(freq))
    expected = int(round(period_delta / base_delta))
    return max(expected, 1)


def aggregate_cleaned_statistics_30min(
    cleaned: pd.DataFrame,
    cfg: Flux30MinConfig,
) -> pd.DataFrame:
    """
    Aggregate minute cleaned data into 30-min statistics.

    The original variable names keep the 30-min mean values required by the
    flux calculations. Optional distribution diagnostics are stored as
    ``std_<column>``, ``q01_<column>`` and ``q99_<column>`` by default.
    """
    if not isinstance(cleaned.index, pd.DatetimeIndex):
        raise ValueError("cleaned must have a DatetimeIndex.")

    validate_required_flux_columns(cleaned, cfg)
    df = ensure_numeric_flux_columns(cleaned, required_flux_columns(cfg)).sort_index()
    if df.index.has_duplicates:
        warnings.warn("Duplicated timestamps found. They will be averaged before aggregation.", RuntimeWarning)
        df = df.groupby(level=0).mean(numeric_only=True)

    expected_n = infer_expected_samples_per_period(df.index, cfg.freq)
    required_cols = required_flux_columns(cfg)

    mean_df = df[required_cols].resample(cfg.freq).mean()
    count_df = df[required_cols].resample(cfg.freq).count()

    if getattr(cfg, "include_distribution_stats", True):
        std_df = df[required_cols].resample(cfg.freq).std()
        q_low = float(getattr(cfg, "lower_quantile", 0.01))
        q_high = float(getattr(cfg, "upper_quantile", 0.99))
        q_low_df = df[required_cols].resample(cfg.freq).quantile(q_low)
        q_high_df = df[required_cols].resample(cfg.freq).quantile(q_high)

        q_low_label = f"q{int(round(q_low * 100)):02d}"
        q_high_label = f"q{int(round(q_high * 100)):02d}"

        for col in required_cols:
            mean_df[f"std_{col}"] = std_df[col]
            mean_df[f"{q_low_label}_{col}"] = q_low_df[col]
            mean_df[f"{q_high_label}_{col}"] = q_high_df[col]

    availability = count_df / expected_n
    min_availability_by_period = availability.min(axis=1)
    mean_df["availability_min"] = min_availability_by_period
    mean_df["expected_samples"] = expected_n

    for col in required_cols:
        mean_df[f"availability_{col}"] = availability[col]

    return mean_df


def optimized_pre_qc_30min(df30: pd.DataFrame, cfg: Flux30MinConfig) -> pd.Series:
    """Vectorized categorical pre-QC for 30-min aggregated records."""
    top_z = max(cfg.heights_m)
    bottom_z = min(cfg.heights_m)

    wind_bottom = cfg.wind_cols[bottom_z]
    wind_top = cfg.wind_cols[top_z]
    temp_bottom = cfg.temp_cols[bottom_z]
    temp_top = cfg.temp_cols[top_z]
    q_bottom = cfg.q_cols[bottom_z]
    q_top = cfg.q_cols[top_z]
    theta_bottom = cfg.theta_v_cols[bottom_z]
    theta_top = cfg.theta_v_cols[top_z]

    critical_cols = [wind_bottom, wind_top, temp_bottom, temp_top, q_bottom, q_top, theta_bottom, theta_top, cfg.pressure_col]
    flags = pd.Series(0, index=df30.index, dtype="int16")

    if "availability_min" in df30.columns:
        low_availability = df30["availability_min"] < cfg.min_availability
        flags.loc[low_availability] = 8

    missing = df30[critical_cols].isna().any(axis=1)
    flags.loc[(flags == 0) & missing] = 4

    invalid = (
        (df30[wind_bottom] < 0)
        | (df30[wind_top] < 0)
        | (df30[cfg.pressure_col] <= 0)
        | (df30[temp_bottom] < -80)
        | (df30[temp_top] < -80)
        | (df30[temp_bottom] > 60)
        | (df30[temp_top] > 60)
        | (df30[theta_bottom] <= 0)
        | (df30[theta_top] <= 0)
    )
    flags.loc[(flags == 0) & invalid] = 6

    low_wind = df30[wind_top] < cfg.min_top_wind_ms
    flags.loc[(flags == 0) & low_wind] = 1

    weak_wind_shear = (df30[wind_top] - df30[wind_bottom]).abs() < cfg.min_abs_wind_shear_ms
    flags.loc[(flags == 0) & weak_wind_shear] = 2

    weak_temp = (df30[temp_top] - df30[temp_bottom]).abs() < cfg.min_abs_temp_diff_K
    flags.loc[(flags == 0) & weak_temp] = 5

    weak_q = (df30[q_top] - df30[q_bottom]).abs() < cfg.min_abs_q_diff
    flags.loc[(flags == 0) & weak_q] = 7

    level_valid_count = pd.Series(0, index=df30.index, dtype="int16")
    for z in cfg.heights_m:
        cols_z = [cfg.wind_cols[z], cfg.temp_cols[z], cfg.q_cols[z], cfg.theta_v_cols[z]]
        level_valid_count += (~df30[cols_z].isna().any(axis=1)).astype("int16")
    insufficient = level_valid_count < cfg.min_valid_levels_most
    flags.loc[(flags == 0) & insufficient] = 3

    return flags


def multi_layer_anchored_brn_30min(row: pd.Series, cfg: Flux30MinConfig) -> List[float]:
    """30-min BRN using the same core as minute BRN."""
    return multi_layer_anchored_brn_minute(row, cfg)


def fit_most_profile_30min(row: pd.Series, cfg: Flux30MinConfig) -> List[float]:
    """30-min MOST profile fitting. Returns [u_star, QH, QE, L, status]."""
    tower_h = np.asarray(cfg.heights_m, dtype=float)
    z_eff = tower_h - cfg.displacement_height_m
    log_z = np.log(z_eff)

    result = fit_most_profile_minute(row, log_z, z_eff, cfg)
    if int(result[4]) != 0 or cfg.min_profile_r2 <= 0:
        return result

    try:
        U = np.asarray([row[cfg.wind_cols[z]] for z in cfg.heights_m], dtype=float)
        T_K = np.asarray([row[cfg.temp_cols[z]] + 273.15 for z in cfg.heights_m], dtype=float)
        q = np.asarray([row[cfg.q_cols[z]] for z in cfg.heights_m], dtype=float)
        valid = np.isfinite(U) & np.isfinite(T_K) & np.isfinite(q) & (U >= 0) & (T_K > 0)
        if valid.sum() >= cfg.min_valid_levels_most:
            _, r2_u = fast_ols_slope_r2(log_z[valid], U[valid])
            _, r2_t = fast_ols_slope_r2(log_z[valid], T_K[valid])
            _, r2_q = fast_ols_slope_r2(log_z[valid], q[valid])
            if np.nanmin([r2_u, r2_t, r2_q]) < cfg.min_profile_r2:
                return [np.nan, np.nan, np.nan, np.nan, 5]
    except (KeyError, ValueError, TypeError):
        return [np.nan, np.nan, np.nan, np.nan, 1]

    return result


def run_30min_flux_pipeline(
    cleaned: pd.DataFrame,
    cfg: Optional[Flux30MinConfig] = None,
    *,
    verbose: bool = True,
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """Aggregate cleaned minute data and run 30-min MOST and BRN_ANC flux estimation."""
    if cfg is None:
        cfg = Flux30MinConfig()

    if verbose:
        print("--- 1. Aggregating cleaned data to 30-min statistics ---")
    df30 = aggregate_cleaned_statistics_30min(cleaned, cfg)
    df30["Input_QC_Flag"] = optimized_pre_qc_30min(df30, cfg)
    df30["Input_QC_Label"] = df30["Input_QC_Flag"].map(INPUT_QC_FLAGS)

    eligible = df30[df30["Input_QC_Flag"] == 0].copy()
    if verbose:
        pct = np.nan if len(df30) == 0 else 100.0 * len(eligible) / len(df30)
        print(f"Eligible 30-min records: {len(eligible):,} of {len(df30):,} ({pct:.2f}%)")

    if eligible.empty:
        warnings.warn("No 30-min records passed pre-calculation QC.")
        report = build_30min_flux_report(df30, pd.Index([]), cfg)
        return df30, report

    iterator = eligible.iterrows()
    if cfg.progress:
        iterator = progress_iterator(iterator, total=len(eligible), desc="MOST 30min")
    if verbose:
        print("\n--- 2. Calculating 30-min MOST fluxes ---")
    most_list = [fit_most_profile_30min(row, cfg) for _, row in iterator]
    most_raw = pd.DataFrame(
        most_list,
        columns=["u_star_MOST", "QH_Wm2_MOST", "QE_Wm2_MOST", "L_MOST", "Status_MOST"],
        index=eligible.index,
    )
    most_raw["Status_Label_MOST"] = most_raw["Status_MOST"].astype("Int64").map(METHOD_STATUS_FLAGS)

    iterator = eligible.iterrows()
    if cfg.progress:
        iterator = progress_iterator(iterator, total=len(eligible), desc="BRN_ANC 30min")
    if verbose:
        print("\n--- 3. Calculating 30-min BRN_ANC fluxes ---")
    brn_list = [multi_layer_anchored_brn_30min(row, cfg) for _, row in iterator]
    brn_raw = pd.DataFrame(
        brn_list,
        columns=["u_star_BRN_ANC", "QH_Wm2_BRN_ANC", "QE_Wm2_BRN_ANC", "Ri_b_BRN_ANC", "Status_BRN_ANC"],
        index=eligible.index,
    )
    brn_raw["Status_Label_BRN_ANC"] = brn_raw["Status_BRN_ANC"].astype("Int64").map(METHOD_STATUS_FLAGS)

    if verbose:
        print("\n--- 4. Applying 30-min post-QC ---")
    most_final = apply_post_qc_flux_outputs(
        most_raw,
        suffix="_MOST",
        cfg=cfg,
        stability_col="L_MOST",
        stability_range=cfg.L_range_m,
    )
    brn_final = apply_post_qc_flux_outputs(
        brn_raw,
        suffix="_BRN_ANC",
        cfg=cfg,
        stability_col="Ri_b_BRN_ANC",
        stability_range=cfg.rib_range,
    )

    final_df = pd.concat([df30, most_final, brn_final], axis=1)

    for method in ["MOST", "BRN_ANC"]:
        flag_col = f"QC_Flag_{method}"
        label_col = f"QC_Label_{method}"
        status_col = f"Status_{method}"

        if flag_col in final_df.columns:
        # Los registros que nunca fueron elegibles por pre-QC deben quedar como NaN,
        # no como QC_Flag = 9. El 9 queda reservado para errores reales.
            final_df.loc[final_df["Input_QC_Flag"] != 0, flag_col] = np.nan

        # Si fue elegible pero no tiene flag, clasificar como salida faltante.
            eligible_missing_flag = (
                (final_df["Input_QC_Flag"] == 0) &
                (final_df[flag_col].isna())
            )
            final_df.loc[eligible_missing_flag, flag_col] = 6

            final_df[label_col] = final_df[flag_col].map(POST_QC_FLAGS)

    report = build_30min_flux_report(final_df, eligible.index, cfg)
    if verbose:
        print_30min_flux_report(report)

    return final_df, report

def audit_status_vs_qc(final_df: pd.DataFrame) -> Dict[str, pd.DataFrame]:
    """
    Auditoría cruzada entre Status_* y QC_Flag_*.

    Status_* indica si el método pudo calcular.
    QC_Flag_* indica si la salida calculada pasó los filtros físicos.

    Criterios esperados:
    - Status == 0 y QC_Flag == 0: salida válida.
    - Status != 0 y QC_Flag == 5: método no pasó.
    - QC_Flag == 9 debe ser raro.
    """

    out: Dict[str, pd.DataFrame] = {}

    for method in ["MOST", "BRN_ANC"]:

        status_col = f"Status_{method}"
        qc_col = f"QC_Flag_{method}"

        if status_col not in final_df.columns:
            print(f"[audit_status_vs_qc] Missing column: {status_col}")
            continue

        if qc_col not in final_df.columns:
            print(f"[audit_status_vs_qc] Missing column: {qc_col}")
            continue

        out[method] = pd.crosstab(
            final_df[status_col],
            final_df[qc_col],
            dropna=False,
        )

    return out


def build_30min_flux_report(final_df: pd.DataFrame, eligible_index: pd.Index, cfg: Flux30MinConfig) -> Dict[str, Any]:
    summary = summarize_flux_results(final_df, eligible_index, methods=["MOST", "BRN_ANC"])
    report: Dict[str, Any] = {
        "configuration": {
            "freq": cfg.freq,
            "min_availability": cfg.min_availability,
            "heights_m": cfg.heights_m,
            "displacement_height_m": cfg.displacement_height_m,
            "use_moist_air_density": cfg.use_moist_air_density,
            "include_distribution_stats": cfg.include_distribution_stats,
            "lower_quantile": cfg.lower_quantile,
            "upper_quantile": cfg.upper_quantile,
        },
        "summary": summary,
        "input_qc_counts": final_df["Input_QC_Flag"].value_counts(dropna=False).sort_index() if "Input_QC_Flag" in final_df else pd.Series(dtype=int),
        "post_qc_counts": {},
        "method_status_counts": {},
    }

    for method in ["MOST", "BRN_ANC"]:
        flag_col = f"QC_Flag_{method}"
        status_col = f"Status_{method}"
        if flag_col in final_df:
            report["post_qc_counts"][method] = final_df[flag_col].value_counts(dropna=False).sort_index()
        if status_col in final_df:
            report["method_status_counts"][method] = final_df[status_col].value_counts(dropna=False).sort_index()

    report["paired_comparison"] = build_paired_comparison_table(final_df)  
    report["sign_consistency_audit"] = audit_flux_sign_consistency(final_df, cfg)    
    report["hourly_paired_audit"] = build_hourly_paired_audit(final_df)  
    report["extreme_flux_audit"] = audit_extreme_fluxes(final_df)
    report["status_vs_qc_audit"] = audit_status_vs_qc(final_df)

    return report

