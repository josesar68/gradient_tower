def calculate_pair_brn_core(
    u1: float,
    u2: float,
    t1_K: float,
    t2_K: float,
    q1: float,
    q2: float,
    thv1_K: float,
    thv2_K: float,
    z1_m: float,
    z2_m: float,
    P_Pa: float,
    cfg: FluxConfig,
) -> List[float]:
    """Estimate [u_star, QH, QE, Ri_b, status] for a vertical pair with BRN."""
    values = [u1, u2, t1_K, t2_K, q1, q2, thv1_K, thv2_K, z1_m, z2_m, P_Pa]
    if not np.all(np.isfinite(values)):
        return [np.nan, np.nan, np.nan, np.nan, 1]
    if z2_m <= z1_m:
        return [np.nan, np.nan, np.nan, np.nan, 2]
    if u1 < 0 or u2 < 0 or P_Pa <= 0 or t1_K <= 0 or t2_K <= 0 or thv1_K <= 0 or thv2_K <= 0:
        return [np.nan, np.nan, np.nan, np.nan, 3]

    raw_du = u2 - u1
    du = abs(raw_du) if cfg.use_abs_shear_for_brn else raw_du
    du = max(du, cfg.min_du_ms)

    dT = t2_K - t1_K
    dq = q2 - q1
    dtheta_v = thv2_K - thv1_K
    theta_v_mean = 0.5 * (thv1_K + thv2_K)
    if theta_v_mean <= 0:
        return [np.nan, np.nan, np.nan, np.nan, 3]

    Ri_b = (G * dtheta_v * (z2_m - z1_m)) / (theta_v_mean * du**2)
    if not np.isfinite(Ri_b):
        return [np.nan, np.nan, np.nan, np.nan, 1]

    if Ri_b < 0:
        Ri_eff = max(Ri_b, cfg.rib_min_unstable)
        f_m = (1.0 - cfg.D_M * Ri_eff) ** (1.0 / 3.0)
        f_h = (1.0 - cfg.D_H * Ri_eff) ** (1.0 / 3.0)
        f_q = (1.0 - cfg.D_Q * Ri_eff) ** (1.0 / 3.0)
    else:
        if Ri_b > cfg.rib_critical:
            return [np.nan, np.nan, np.nan, float(Ri_b), 8]
        stable_factor = max(0.0, 1.0 - 5.0 * Ri_b) ** 2
        f_m = f_h = f_q = stable_factor

    u_ref = max(u2, cfg.min_top_wind_ms)
    u_star = u_ref * cfg.C_M * f_m
    H_kin = -dT * u_star * cfg.C_H * f_h
    q_kin = -dq * u_star * cfg.C_Q * f_q

    T_layer = 0.5 * (t1_K + t2_K)
    q_layer = 0.5 * (q1 + q2)
    rho = air_density_moist(P_Pa, T_layer, q_layer) if cfg.use_moist_air_density else air_density_dry(P_Pa, T_layer)
    Lv = latent_heat_vaporization(T_layer)
    if not np.isfinite(rho) or not np.isfinite(Lv):
        return [np.nan, np.nan, np.nan, float(Ri_b), 7]

    QH = rho * CP * H_kin
    QE = rho * Lv * q_kin
    return [float(u_star), float(QH), float(QE), float(Ri_b), 0]


def multi_layer_anchored_brn_minute(row: pd.Series, cfg: FluxConfig) -> List[float]:
    """Minute BRN using the lowest tower level as anchor. Returns [u*, QH, QE, Ri_b, status]."""
    z_sorted = sorted(cfg.heights_m)
    z0 = z_sorted[0]
    try:
        u0 = row[cfg.wind_cols[z0]]
        t0_K = row[cfg.temp_cols[z0]] + 273.15
        q0 = row[cfg.q_cols[z0]]
        thv0 = row[cfg.theta_v_cols[z0]]
        P = row[cfg.pressure_col]
    except KeyError:
        return [np.nan, np.nan, np.nan, np.nan, 1]

    if not np.all(np.isfinite([u0, t0_K, q0, thv0, P])):
        return [np.nan, np.nan, np.nan, np.nan, 1]

    results: List[List[float]] = []
    statuses: List[int] = []
    for z in z_sorted[1:]:
        try:
            result = calculate_pair_brn_core(
                u1=u0,
                u2=row[cfg.wind_cols[z]],
                t1_K=t0_K,
                t2_K=row[cfg.temp_cols[z]] + 273.15,
                q1=q0,
                q2=row[cfg.q_cols[z]],
                thv1_K=thv0,
                thv2_K=row[cfg.theta_v_cols[z]],
                z1_m=z0,
                z2_m=z,
                P_Pa=P,
                cfg=cfg,
            )
        except (KeyError, TypeError, ValueError, FloatingPointError):
            result = [np.nan, np.nan, np.nan, np.nan, 9]
        results.append(result[:4])
        statuses.append(int(result[4]))

    valid_results = [r for r, st in zip(results, statuses) if st == 0 and np.all(np.isfinite(r[:3]))]
    if not valid_results:
        status = min(statuses) if statuses else 1
        if status == 0:
            status = 5
        return [np.nan, np.nan, np.nan, np.nan, status]

    med = list(np.nanmedian(np.asarray(valid_results, dtype=float), axis=0))
    return [float(med[0]), float(med[1]), float(med[2]), float(med[3]), 0]


