def compute_qc_flag_diurnal_counts(
    final_df: pd.DataFrame,
    *,
    flag_cols: Optional[Sequence[str]] = None,
    bin_minutes: int = 30,
) -> Dict[str, pd.DataFrame]:
    """Count QC flags by local time bin within the day.

    The output tables have one row per time-of-day bin and one column per flag.
    For 30-min flux products, the default creates 48 rows. The same function can
    also summarize minute products into half-hour bins without recalculating
    fluxes.
    """
    if not isinstance(final_df.index, pd.DatetimeIndex):
        raise ValueError("final_df must use a DatetimeIndex.")
    if 60 % bin_minutes != 0:
        raise ValueError("bin_minutes must divide 60 exactly.")

    if flag_cols is None:
        flag_cols = ["Input_QC_Flag", "QC_Flag_MOST", "QC_Flag_BRN_ANC"]
    qc_cols = [c for c in flag_cols if c in final_df.columns]

    bins_per_day = int(24 * 60 / bin_minutes)
    bin_index = pd.Index(range(bins_per_day), name="time_bin")
    out: Dict[str, pd.DataFrame] = {}

    minutes = final_df.index.hour * 60 + final_df.index.minute
    time_bin = (minutes // bin_minutes).astype(int)
    bin_start_minutes = bin_index.to_numpy() * bin_minutes
    time_labels = [f"{m // 60:02d}:{m % 60:02d}" for m in bin_start_minutes]

    for col in qc_cols:
        qc_raw = final_df[col]
        qc_numeric = pd.to_numeric(qc_raw, errors="coerce")
        qc_labels = qc_raw.astype("object").where(~pd.isna(qc_raw), "NaN")
        whole_numeric = qc_numeric.notna() & np.isclose(qc_numeric, np.round(qc_numeric))
        qc_labels.loc[whole_numeric] = qc_numeric.loc[whole_numeric].round().astype(int).astype(str)
        work = pd.DataFrame({"time_bin": time_bin, "qc_flag": qc_labels.to_numpy()}, index=final_df.index)
        counts = (
            work.groupby(["time_bin", "qc_flag"], dropna=False)
            .size()
            .unstack("qc_flag", fill_value=0)
            .reindex(bin_index, fill_value=0)
        )
        counts.insert(0, "time_label", time_labels)
        counts.insert(1, "hour_decimal", bin_start_minutes / 60.0)
        out[col] = counts
    return out


def _qc_flag_sort_key(value: object) -> Tuple[int, float, str]:
    if isinstance(value, str) and value == "NaN":
        return (1, np.inf, value)
    try:
        return (0, float(value), str(value))
    except (TypeError, ValueError):
        return (0, np.inf, str(value))


