def fast_ols_slope(x: np.ndarray, y: np.ndarray) -> float:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    valid = np.isfinite(x) & np.isfinite(y)
    x = x[valid]
    y = y[valid]
    n = len(x)
    if n < 2:
        return np.nan
    sx = np.sum(x)
    sy = np.sum(y)
    sxx = np.sum(x * x)
    sxy = np.sum(x * y)
    denominator = n * sxx - sx**2
    if abs(denominator) < 1.0e-12:
        return np.nan
    return float((n * sxy - sx * sy) / denominator)


def fast_ols_slope_r2(x: np.ndarray, y: np.ndarray) -> Tuple[float, float]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    valid = np.isfinite(x) & np.isfinite(y)
    x = x[valid]
    y = y[valid]
    if len(x) < 2:
        return np.nan, np.nan
    slope = fast_ols_slope(x, y)
    if not np.isfinite(slope):
        return np.nan, np.nan
    intercept = float(np.nanmean(y) - slope * np.nanmean(x))
    yhat = intercept + slope * x
    ss_res = float(np.sum((y - yhat) ** 2))
    ss_tot = float(np.sum((y - np.nanmean(y)) ** 2))
    r2 = np.nan if ss_tot <= 0 else 1.0 - ss_res / ss_tot
    return float(slope), float(r2)


def psi_m_businger_dyer(zeta: np.ndarray, max_abs_zeta: float = 10.0) -> np.ndarray:
    zeta = np.asarray(zeta, dtype=float)
    zeta = np.clip(zeta, -max_abs_zeta, max_abs_zeta)
    psi = np.zeros_like(zeta, dtype=float)

    unstable = zeta < 0
    if np.any(unstable):
        x = (1.0 - 16.0 * zeta[unstable]) ** 0.25
        psi[unstable] = (
            2.0 * np.log((1.0 + x) / 2.0)
            + np.log((1.0 + x**2) / 2.0)
            - 2.0 * np.arctan(x)
            + np.pi / 2.0
        )

    stable = zeta >= 0
    if np.any(stable):
        psi[stable] = -5.0 * zeta[stable]

    return psi


def psi_h_businger_dyer(zeta: np.ndarray, max_abs_zeta: float = 10.0) -> np.ndarray:
    zeta = np.asarray(zeta, dtype=float)
    zeta = np.clip(zeta, -max_abs_zeta, max_abs_zeta)
    psi = np.zeros_like(zeta, dtype=float)

    unstable = zeta < 0
    if np.any(unstable):
        y = (1.0 - 16.0 * zeta[unstable]) ** 0.5
        psi[unstable] = 2.0 * np.log((1.0 + y) / 2.0)

    stable = zeta >= 0
    if np.any(stable):
        psi[stable] = -5.0 * zeta[stable]

    return psi


def air_density_dry(P_Pa: float, T_K: float) -> float:
    if not np.isfinite(P_Pa) or not np.isfinite(T_K) or T_K <= 0 or P_Pa <= 0:
        return np.nan
    return float(P_Pa / (RD * T_K))


def air_density_moist(P_Pa: float, T_K: float, q_kgkg: float) -> float:
    if not np.all(np.isfinite([P_Pa, T_K, q_kgkg])) or T_K <= 0 or P_Pa <= 0:
        return np.nan
    Tv = T_K * (1.0 + 0.61 * q_kgkg)
    if Tv <= 0:
        return np.nan
    return float(P_Pa / (RD * Tv))


def latent_heat_vaporization(T_K: float) -> float:
    if not np.isfinite(T_K):
        return np.nan
    return float(2.501e6 - 2370.0 * (T_K - 273.15))


def safe_median_result(results: List[List[float]], n_outputs: int) -> List[float]:
    valid = [r for r in results if len(r) == n_outputs and np.all(np.isfinite(r[: min(3, n_outputs)]))]
    if not valid:
        return [np.nan] * n_outputs
    return list(np.nanmedian(np.asarray(valid, dtype=float), axis=0))


