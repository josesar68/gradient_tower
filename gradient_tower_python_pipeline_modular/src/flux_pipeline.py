def run_minute_flux_pipeline(
    cleaned: pd.DataFrame,
    cfg: Optional[FluxConfig] = None,
    *,
    include_pre_qc_diagnostics: bool = True,
    verbose: bool = True,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Run minute-resolution MOST and BRN_ANC flux estimation."""
    if cfg is None:
        cfg = FluxConfig()
    if not isinstance(cleaned.index, pd.DatetimeIndex):
        raise ValueError("cleaned must have a DatetimeIndex.")

    validate_required_flux_columns(cleaned, cfg)
    df = ensure_numeric_flux_columns(cleaned, required_flux_columns(cfg))
    df = df.sort_index()

    tower_h = np.asarray(cfg.heights_m, dtype=float)
    z_eff = tower_h - cfg.displacement_height_m
    log_z = np.log(z_eff)

    if verbose:
        print("--- 1. Minute pre-QC of input variables ---")
    df["Input_QC_Flag"] = pre_calculation_qc_minute(df, cfg)
    df["Input_QC_Label"] = df["Input_QC_Flag"].map(INPUT_QC_FLAGS)

    if include_pre_qc_diagnostics:
        df = pd.concat([df, build_minute_pre_qc_diagnostics(df, cfg)], axis=1)

    eligible = df[df["Input_QC_Flag"] == 0].copy()
    if verbose:
        pct = np.nan if len(df) == 0 else 100.0 * len(eligible) / len(df)
        print(f"Eligible records: {len(eligible):,} of {len(df):,} ({pct:.2f}%)")

    if eligible.empty:
        warnings.warn("No records passed minute pre-calculation QC. Returning input with QC flags only.")
        return df, pd.DataFrame()

    iterator = eligible.iterrows()
    if cfg.progress:
        iterator = progress_iterator(iterator, total=len(eligible), desc="MOST minute")
    if verbose:
        print("\n--- 2. Calculating minute MOST fluxes ---")
    most_list = [fit_most_profile_minute(row, log_z, z_eff, cfg) for _, row in iterator]
    most_raw = pd.DataFrame(
        most_list,
        columns=["u_star_MOST", "QH_Wm2_MOST", "QE_Wm2_MOST", "L_MOST", "Status_MOST"],
        index=eligible.index,
    )
    most_raw["Status_Label_MOST"] = most_raw["Status_MOST"].astype("Int64").map(METHOD_STATUS_FLAGS)

    iterator = eligible.iterrows()
    if cfg.progress:
        iterator = progress_iterator(iterator, total=len(eligible), desc="BRN_ANC minute")
    if verbose:
        print("\n--- 3. Calculating minute anchored multi-layer BRN fluxes ---")
    brn_list = [multi_layer_anchored_brn_minute(row, cfg) for _, row in iterator]
    brn_raw = pd.DataFrame(
        brn_list,
        columns=["u_star_BRN_ANC", "QH_Wm2_BRN_ANC", "QE_Wm2_BRN_ANC", "Ri_b_BRN_ANC", "Status_BRN_ANC"],
        index=eligible.index,
    )
    brn_raw["Status_Label_BRN_ANC"] = brn_raw["Status_BRN_ANC"].astype("Int64").map(METHOD_STATUS_FLAGS)

    if verbose:
        print("\n--- 4. Applying minute post-QC ---")
    most_final = apply_post_qc_flux_outputs(
        most_raw,
        suffix="_MOST",
        cfg=cfg,
        stability_col="L_MOST",
        stability_range=cfg.L_range_m,
    )
    brn_final = apply_post_qc_flux_outputs(
        brn_raw,
        suffix="_BRN_ANC",
        cfg=cfg,
        stability_col="Ri_b_BRN_ANC",
        stability_range=cfg.rib_range,
    )

    final_df = pd.concat([df, most_final, brn_final], axis=1)
    for method in ["MOST", "BRN_ANC"]:
        flag_col = f"QC_Flag_{method}"
        if flag_col in final_df.columns:
            final_df[flag_col] = final_df[flag_col].fillna(9).astype("int16")
            final_df[f"QC_Label_{method}"] = final_df[flag_col].map(POST_QC_FLAGS)

    summary = summarize_flux_results(final_df, eligible.index, methods=["MOST", "BRN_ANC"])
    if verbose:
        print("\n--- 5. Minute final audit report ---")
        if not summary.empty:
            print(summary.to_string(float_format=lambda x: f"{x:.2f}"))
        print_qc_dictionaries()

    return final_df, summary


