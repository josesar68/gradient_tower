def _validate_flux_config_common(cfg: FluxConfig) -> None:
    heights = np.asarray(cfg.heights_m, dtype=float)
    if len(heights) < 2:
        raise ValueError("At least two tower heights are required.")
    if len(set(heights.tolist())) != len(heights):
        raise ValueError("heights_m contains duplicated values.")
    if cfg.displacement_height_m < 0:
        raise ValueError("displacement_height_m must be non-negative.")
    if np.any(heights <= cfg.displacement_height_m):
        raise ValueError("All heights must be greater than displacement_height_m.")

    for name, mapping in {
        "wind_cols": cfg.wind_cols,
        "temp_cols": cfg.temp_cols,
        "q_cols": cfg.q_cols,
        "theta_v_cols": cfg.theta_v_cols,
    }.items():
        for z in mapping:
            if float(z) not in set(heights.tolist()):
                raise ValueError(f"Height {z} in {name} is not present in heights_m.")

    for name, value in {
        "C_M": cfg.C_M,
        "C_H": cfg.C_H,
        "C_Q": cfg.C_Q,
        "D_M": cfg.D_M,
        "D_H": cfg.D_H,
        "D_Q": cfg.D_Q,
        "min_top_wind_ms": cfg.min_top_wind_ms,
        "min_abs_wind_shear_ms": cfg.min_abs_wind_shear_ms,
        "min_abs_temp_diff_K": cfg.min_abs_temp_diff_K,
        "min_du_ms": cfg.min_du_ms,
    }.items():
        if value < 0:
            raise ValueError(f"{name} must be non-negative.")


