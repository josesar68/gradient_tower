def save_30min_energy_fluxes_to_netcdf(
    final_df_30m: pd.DataFrame,
    output_nc: str | Path = "data_nc/OGHYO_30min_EnergyFluxes_MOST_BRN_ANC.nc",
    *,
    cfg=None,
    report: Optional[Dict[str, Any]] = None,
    timezone: str = "America/Lima",
    expected_freq: str = "30min",
    latitude: Optional[float] = None,
    longitude: Optional[float] = None,
    altitude_m: Optional[float] = 3315.0,
    engine: str = "netcdf4",
    zlib: bool = True,
    complevel: int = 4,
    float_dtype: str = "float32",
    save_audit_csv: bool = True,
    save_audit_groups: bool = True,
    overwrite: bool = True,
    drop_text_labels: bool = False,
) -> Tuple[Path, xr.Dataset, pd.DataFrame, Dict[str, str]]:
    """
    Save a 30-min energy flux DataFrame to NetCDF including all QC/status/flag columns.

    Parameters
    ----------
    final_df_30m : pd.DataFrame
        DataFrame with 30-min energy fluxes and QC columns.
    output_nc : str or Path
        Output NetCDF file path.
    timezone : str
        Timezone represented by the DataFrame index.
    expected_freq : str
        Expected temporal frequency, e.g. '30min'.
    latitude, longitude, altitude_m : float, optional
        Site metadata.
    engine : str
        NetCDF backend engine. Recommended: 'netcdf4'.
    zlib : bool
        Apply compression to numeric variables.
    complevel : int
        Compression level.
    float_dtype : str
        Floating-point storage dtype. Recommended: 'float32' for compact files.
    save_audit_csv : bool
        Save an audit CSV next to the NetCDF file.
    overwrite : bool
        If False, raise an error if output file exists.
    drop_text_labels : bool
        If True, omit repeated human-readable label/status text columns from
        the NetCDF and keep their dictionaries in global attributes.

    Returns
    -------
    output_nc : Path
        Saved NetCDF path.
    ds : xr.Dataset
        Dataset saved to disk.
    audit : pd.DataFrame
        Validation report.
    column_name_map : dict
        Mapping from original DataFrame column names to NetCDF variable names.
    """

    output_nc = Path(output_nc)
    output_nc.parent.mkdir(parents=True, exist_ok=True)

    if output_nc.exists() and not overwrite:
        raise FileExistsError(f"Output file already exists: {output_nc}")

    # -------------------------------------------------------------------------
    # Audit before saving
    # -------------------------------------------------------------------------
    audit = validate_30min_flux_dataframe(
        final_df_30m,
        expected_freq=expected_freq,
        require_datetime_index=True,
        allow_duplicate_times=False,
    )

    failed = audit[audit["status"] == "FAIL"]

    if not failed.empty:
        raise ValueError(
            "The 30-min flux DataFrame did not pass validation:\n"
            + failed.to_string(index=False)
        )

    # -------------------------------------------------------------------------
    # Convert to xarray
    # -------------------------------------------------------------------------
    ds, column_name_map = dataframe_to_flux_netcdf_dataset(
        final_df_30m,
        cfg=cfg,
        report=report,
        timezone=timezone,
        original_frequency=expected_freq,
        latitude=latitude,
        longitude=longitude,
        altitude_m=altitude_m,
        drop_text_labels=drop_text_labels,
    )

    # -------------------------------------------------------------------------
    # Encoding
    # -------------------------------------------------------------------------
    encoding = build_netcdf_encoding(
        ds,
        time_name="time",
        zlib=zlib,
        complevel=complevel,
        float_dtype=float_dtype,
    )

    # -------------------------------------------------------------------------
    # Save NetCDF
    # -------------------------------------------------------------------------
    ds.to_netcdf(
        output_nc,
        mode="w",
        engine=engine,
        encoding=encoding,
    )

    # ------------------------------------------------------------------
    # APPEND AUDIT TABLES AS NETCDF GROUPS
    # ------------------------------------------------------------------
    if save_audit_groups and report is not None:

        append_audit_tables_to_netcdf(
            output_nc,
            report,
            engine=engine,
        )

    # -------------------------------------------------------------------------
    # Optional audit CSV
    # -------------------------------------------------------------------------
    if save_audit_csv:
        audit_csv = output_nc.with_suffix(".audit.csv")
        audit.to_csv(audit_csv, index=False)

        name_map_csv = output_nc.with_suffix(".column_name_map.csv")
        pd.DataFrame(
            [{"original_column": k, "netcdf_variable": v} for k, v in column_name_map.items()]
        ).to_csv(name_map_csv, index=False)

    # -------------------------------------------------------------------------
    # Reopen verification
    # -------------------------------------------------------------------------
    with xr.open_dataset(output_nc, engine=engine) as ds_check:
        n_time = ds_check.sizes.get("time", 0)
        n_vars = len(ds_check.data_vars)

    print("\n=== NETCDF SAVED SUCCESSFULLY ===")
    print(f"File       : {output_nc}")
    print(f"Time steps : {n_time}")
    print(f"Variables  : {n_vars}")

    if save_audit_csv:
        print(f"Audit CSV  : {output_nc.with_suffix('.audit.csv')}")
        print(f"Name map   : {output_nc.with_suffix('.column_name_map.csv')}")

    return output_nc, ds, audit, column_name_map


