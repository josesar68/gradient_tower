def dataframe_to_flux_netcdf_dataset(
    final_df_30m: pd.DataFrame,
    *,
    cfg=None,
    report: Optional[Dict[str, Any]] = None,
    time_name: str = "time",
    timezone: str = "America/Lima",
    original_frequency: str = "30min",
    title: str = "30-min energy fluxes from OGHYO gradient tower",
    institution: str = "Instituto Geofísico del Perú (IGP)",
    site_name: str = "Observatorio Geofísico de Huancayo",
    latitude: Optional[float] = None,
    longitude: Optional[float] = None,
    altitude_m: Optional[float] = 3315.0,
    source: str = "Gradient tower flux processing using MOST and BRN_ANC methods",
    comment: str = "Energy fluxes aggregated to 30-minute temporal resolution.",
    drop_text_labels: bool = False,
) -> Tuple[xr.Dataset, Dict[str, str]]:
    """
    Convert a 30-min flux DataFrame to an xarray Dataset ready for NetCDF export.

    Returns
    -------
    ds : xr.Dataset
        Dataset ready to save.
    column_name_map : dict
        Original-column to NetCDF-variable-name mapping.
    """

    df = final_df_30m.copy()

    if not isinstance(df.index, pd.DatetimeIndex):
        raise TypeError("final_df_30m must have a DatetimeIndex before NetCDF export.")

    if df.index.name is None:
        df.index.name = time_name

    # Sort index for NetCDF consistency
    df = df.sort_index()

    if df.index.duplicated().any():
        raise ValueError(
            "final_df_30m contains duplicated timestamps. "
            "Please resolve duplicates before saving to NetCDF."
        )

    omitted_text_label_columns: List[str] = []
    if drop_text_labels:
        df, omitted_text_label_columns = drop_flux_text_label_columns_for_netcdf(df)

    # Sanitize variable names
    df_sanitized, column_name_map = sanitize_dataframe_columns_for_netcdf(df)

    # Convert object columns safely
    for col in df_sanitized.columns:
        if pd.api.types.is_object_dtype(df_sanitized[col]):
            df_sanitized[col] = df_sanitized[col].astype("string").fillna("")

        elif pd.api.types.is_bool_dtype(df_sanitized[col]):
            df_sanitized[col] = df_sanitized[col].astype("int8")

    # Build xarray Dataset
    ds = xr.Dataset(
        coords={
            time_name: pd.to_datetime(df_sanitized.index),
        }
    )

    for original_col, safe_col in column_name_map.items():
        series = df_sanitized[safe_col]

        # Numeric variables
        if pd.api.types.is_numeric_dtype(series):
            data = series.to_numpy()
        else:
            data = series.astype(str).to_numpy()

        ds[safe_col] = xr.DataArray(
            data,
            dims=(time_name,),
            coords={time_name: ds[time_name]},
            attrs=infer_flux_variable_attrs(original_col),
        )

        ds[safe_col].attrs["original_column_name"] = original_col

    # Coordinate attributes
    ds[time_name].attrs.update({
        "long_name": "Time",
        "timezone": timezone,
        "frequency": original_frequency,
        "comment": (
            "Timestamps represent the DataFrame index used during export. "
            "If timezone-naive, timezone is documented in the timezone attribute."
        ),
    })

    # Global attributes
    ds.attrs.update({
        "title": title,
        "institution": institution,
        "site_name": site_name,
        "source": source,
        "history": f"Created from pandas DataFrame on {pd.Timestamp.now().isoformat()}",
        "time_zone": timezone,
        "temporal_resolution": original_frequency,
        "Conventions": "CF-1.8",
        "comment": comment,
        "input_qc_flags": json.dumps(INPUT_QC_FLAGS),
        "post_qc_flags": json.dumps(POST_QC_FLAGS),
        "method_status_flags": json.dumps(METHOD_STATUS_FLAGS),
        "column_name_map": json.dumps(column_name_map),
    })

    if omitted_text_label_columns:
        ds.attrs["text_label_columns_omitted"] = json.dumps(omitted_text_label_columns)
        ds.attrs["text_label_policy"] = (
            "Human-readable label/status text columns were omitted to reduce "
            "NetCDF size. Reconstruct labels from the retained numeric flag/status "
            "variables using input_qc_flags, post_qc_flags and method_status_flags."
        )

    if latitude is not None:
        ds.attrs["latitude"] = float(latitude)

    if longitude is not None:
        ds.attrs["longitude"] = float(longitude)

    if altitude_m is not None:
        ds.attrs["altitude_m"] = float(altitude_m)

        # ------------------------------------------------------------------
    # PIPELINE CONFIGURATION
    # ------------------------------------------------------------------
    if cfg is not None:

        cfg_attrs = [
            "kappa",
            "C_M",
            "D_M",
            "C_H",
            "D_H",
            "C_Q",
            "D_Q",
            "Ri_b_critical",
            "most_tolerance_L_m",
            "most_relative_tolerance",
            "displacement_height_m",
            "min_availability",
            "min_abs_q_diff",
            "include_distribution_stats",
            "lower_quantile",
            "upper_quantile",
        ]

        for attr in cfg_attrs:
            if hasattr(cfg, attr):
                try:
                    value = getattr(cfg, attr)
                    ds.attrs[attr] = int(value) if isinstance(value, bool) else float(value)
                except Exception:
                    ds.attrs[attr] = str(getattr(cfg, attr))    

    ds = sanitize_dataset_attrs_for_netcdf(ds)
    return ds, column_name_map


