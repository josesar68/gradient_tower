def regression_metrics(x: Iterable[float], y: Iterable[float]) -> Dict[str, float]:
    x_arr = np.asarray(x, dtype=float)
    y_arr = np.asarray(y, dtype=float)
    mask = np.isfinite(x_arr) & np.isfinite(y_arr)
    x_arr = x_arr[mask]
    y_arr = y_arr[mask]
    if len(x_arr) < 2:
        return {"n": int(len(x_arr)), "slope": np.nan, "intercept": np.nan, "r2": np.nan,
                "pearson_r": np.nan, "rmse": np.nan, "mae": np.nan, "mbe": np.nan}
    slope, intercept = np.polyfit(x_arr, y_arr, 1)
    yhat = slope * x_arr + intercept
    ss_res = np.sum((y_arr - yhat) ** 2)
    ss_tot = np.sum((y_arr - np.mean(y_arr)) ** 2)
    diff = y_arr - x_arr
    return {
        "n": int(len(x_arr)),
        "slope": float(slope),
        "intercept": float(intercept),
        "r2": float(1.0 - ss_res / ss_tot) if ss_tot > 0 else np.nan,
        "pearson_r": float(np.corrcoef(x_arr, y_arr)[0, 1]),
        "rmse": float(np.sqrt(np.mean(diff**2))),
        "mae": float(np.mean(np.abs(diff))),
        "mbe": float(np.mean(diff)),
    }


def flux_summary_statistics(final_df: pd.DataFrame) -> pd.DataFrame:
    df = standardize_flux_column_names(final_df)
    cols = [
        "QH_Wm2_MOST", "QH_Wm2_BRN_ANC",
        "QE_Wm2_MOST", "QE_Wm2_BRN_ANC",
        "u_star_MOST", "u_star_BRN_ANC",
        "L_MOST", "Ri_b_BRN_ANC",
    ]
    cols = [c for c in cols if c in df.columns]
    if not cols:
        return pd.DataFrame()
    stats = df[cols].describe(percentiles=[0.05, 0.25, 0.50, 0.75, 0.95]).T
    stats["missing"] = df[cols].isna().sum()
    stats["available_pct"] = 100.0 * df[cols].notna().sum() / len(df) if len(df) else np.nan
    return stats


def comparison_statistics_table(final_df: pd.DataFrame) -> pd.DataFrame:
    df = standardize_flux_column_names(final_df)
    comparisons: Dict[str, Dict[str, float]] = {}
    pairs = {
        "QH_Wm2": ("QH_Wm2_MOST", "QH_Wm2_BRN_ANC"),
        "QE_Wm2": ("QE_Wm2_MOST", "QE_Wm2_BRN_ANC"),
        "u_star": ("u_star_MOST", "u_star_BRN_ANC"),
    }
    for name, (xcol, ycol) in pairs.items():
        if {xcol, ycol}.issubset(df.columns):
            comparisons[name] = regression_metrics(df[xcol], df[ycol])
    return pd.DataFrame(comparisons).T


def add_stats_box(ax: plt.Axes, stats: Mapping[str, float]) -> None:
    txt = (
        f"N = {stats['n']}\n"
        f"Slope = {stats['slope']:.3f}\n"
        f"Intercept = {stats['intercept']:.3f}\n"
        f"$R^2$ = {stats['r2']:.3f}\n"
        f"r = {stats['pearson_r']:.3f}\n"
        f"RMSE = {stats['rmse']:.2f}\n"
        f"MAE = {stats['mae']:.2f}\n"
        f"MBE = {stats['mbe']:.2f}"
    )
    ax.text(
        0.03, 0.97, txt,
        transform=ax.transAxes,
        va="top",
        ha="left",
        bbox=dict(boxstyle="round", facecolor="white", edgecolor="0.6", alpha=0.9),
    )


def scatter_comparison_plot(
    ax: plt.Axes,
    x: Iterable[float],
    y: Iterable[float],
    *,
    xlabel: str,
    ylabel: str,
    title: str,
    color: str,
) -> None:
    stats = regression_metrics(x, y)
    x_arr = np.asarray(x, dtype=float)
    y_arr = np.asarray(y, dtype=float)
    mask = np.isfinite(x_arr) & np.isfinite(y_arr)
    x_arr = x_arr[mask]
    y_arr = y_arr[mask]

    if len(x_arr) > 0:
        min_v = np.nanmin(np.r_[x_arr, y_arr])
        max_v = np.nanmax(np.r_[x_arr, y_arr])
        pad = 0.05 * (max_v - min_v) if max_v > min_v else 10.0
        ax.scatter(x_arr, y_arr, s=8, alpha=0.45, edgecolors="none", color=color)
        ax.plot(
            [min_v - pad, max_v + pad],
            [min_v - pad, max_v + pad],
            linestyle="--",
            color=PLOT_COLORS["ONE_TO_ONE"],
            linewidth=1.3,
            label="1:1 line",
        )
        if np.isfinite(stats["slope"]):
            xline = np.linspace(min_v - pad, max_v + pad, 100)
            yline = stats["slope"] * xline + stats["intercept"]
            ax.plot(xline, yline, color=PLOT_COLORS["FIT"], linewidth=1.5, label="Linear fit")
        add_stats_box(ax, stats)
        ax.set_xlim(min_v - pad, max_v + pad)
        ax.set_ylim(min_v - pad, max_v + pad)

    ax.set_title(title, fontweight="bold")
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.grid(True)
    ax.legend(frameon=True)


