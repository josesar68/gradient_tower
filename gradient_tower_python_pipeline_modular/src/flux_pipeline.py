def compute_seasonal_hourly_stats(
    final_df: pd.DataFrame,
    *,
    variables: Sequence[str] = ("QH", "QE", "u_star"),
    use_only_valid_qc: bool = True,
    season_scheme: str = "dry_wet",
) -> Dict[str, pd.DataFrame]:
    df = prepare_flux_plot_df(final_df, use_only_valid_qc=use_only_valid_qc).copy()
    if season_scheme == "dry_wet":
        season_map = SEASON_MAP_DRY_WET
    elif season_scheme == "quarterly":
        season_map = SEASON_MAP_SOUTHERN_HEMISPHERE
    else:
        raise ValueError("season_scheme must be 'dry_wet' or 'quarterly'.")

    df["season"] = df.index.month.map(season_map)
    df["hour"] = df.index.hour + df.index.minute / 60.0

    output: Dict[str, pd.DataFrame] = {}
    col_pairs = {
        "QH": ("QH_Wm2_MOST", "QH_Wm2_BRN_ANC"),
        "QE": ("QE_Wm2_MOST", "QE_Wm2_BRN_ANC"),
        "u_star": ("u_star_MOST", "u_star_BRN_ANC"),
    }
    for var in variables:
        if var not in col_pairs:
            continue
        most_col, brn_col = col_pairs[var]
        if most_col not in df.columns or brn_col not in df.columns:
            continue
        grouped = df.groupby(["season", "hour"])[[most_col, brn_col]]
        mean = grouped.mean().rename(columns={most_col: "MOST_mean", brn_col: "BRN_ANC_mean"})
        std = grouped.std().rename(columns={most_col: "MOST_std", brn_col: "BRN_ANC_std"})
        count = grouped.count().rename(columns={most_col: "MOST_n", brn_col: "BRN_ANC_n"})
        stats = pd.concat([mean, std, count], axis=1).reset_index()
        day_count = (
            df.dropna(subset=[most_col, brn_col], how="all")
            .assign(date=lambda x: x.index.normalize())
            .groupby("season")["date"]
            .nunique()
            .rename("n_days")
            .reset_index()
        )
        output[var] = stats.merge(day_count, on="season", how="left")
    return output


