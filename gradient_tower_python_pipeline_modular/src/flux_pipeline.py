def quick_flux_statistics(ds):
    """
    Compute compact statistics of main fluxes.
    """

    variables = [
        "QH_Wm2_MOST",
        "QH_Wm2_BRN_ANC",
        "QE_Wm2_MOST",
        "QE_Wm2_BRN_ANC",
        "u_star_MOST",
        "u_star_BRN_ANC",
    ]

    rows = []

    for var in variables:

        if var not in ds:
            continue

        s = ds[var].to_series().dropna()

        rows.append({
            "variable": var,
            "count": len(s),
            "mean": s.mean(),
            "std": s.std(),
            "min": s.min(),
            "p05": s.quantile(0.05),
            "median": s.median(),
            "p95": s.quantile(0.95),
            "max": s.max(),
        })

    return pd.DataFrame(rows)


