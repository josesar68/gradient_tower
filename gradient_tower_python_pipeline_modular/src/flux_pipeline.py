def fit_most_profile_minute(
    row: pd.Series,
    log_z_eff: np.ndarray,
    heights_eff: np.ndarray,
    cfg: FluxConfig,
) -> List[float]:
    """Fit MOST profiles. Returns [u_star, QH, QE, L, status]."""
    try:
        U = np.asarray([row[cfg.wind_cols[z]] for z in cfg.heights_m], dtype=float)
        T_K = np.asarray([row[cfg.temp_cols[z]] + 273.15 for z in cfg.heights_m], dtype=float)
        q = np.asarray([row[cfg.q_cols[z]] for z in cfg.heights_m], dtype=float)
        P = float(row[cfg.pressure_col])
    except (KeyError, TypeError, ValueError):
        return [np.nan, np.nan, np.nan, np.nan, 1]

    valid = np.isfinite(U) & np.isfinite(T_K) & np.isfinite(q) & (U >= 0) & (T_K > 0)
    if valid.sum() < cfg.min_valid_levels_most:
        return [np.nan, np.nan, np.nan, np.nan, 4]

    lz = log_z_eff[valid]
    z_v = heights_eff[valid]
    U_v = U[valid]
    T_v = T_K[valid]
    q_v = q[valid]

    m_u = fast_ols_slope(lz, U_v)
    m_t = fast_ols_slope(lz, T_v)
    m_q = fast_ols_slope(lz, q_v)
    if not np.all(np.isfinite([m_u, m_t, m_q])):
        return [np.nan, np.nan, np.nan, np.nan, 1]

    u_star = KAPPA * m_u
    t_star = KAPPA * m_t
    q_star = KAPPA * m_q
    if not np.isfinite(u_star) or u_star <= 0:
        return [np.nan, np.nan, np.nan, np.nan, 5]

    L = cfg.initial_L_unstable_m if t_star < 0 else cfg.initial_L_stable_m
    converged = False

    for _ in range(cfg.max_most_iterations):
        if abs(L) < cfg.min_abs_L_m:
            L = np.sign(L) * cfg.min_abs_L_m if L != 0 else cfg.initial_L_stable_m

        zeta = z_v / L
        pm = psi_m_businger_dyer(zeta, max_abs_zeta=cfg.max_abs_zeta)
        ph = psi_h_businger_dyer(zeta, max_abs_zeta=cfg.max_abs_zeta)

        u_star_new = KAPPA * fast_ols_slope(lz, U_v + (u_star / KAPPA) * pm)
        t_star_new = KAPPA * fast_ols_slope(lz, T_v + (t_star / KAPPA) * ph)
        q_star_new = KAPPA * fast_ols_slope(lz, q_v + (q_star / KAPPA) * ph)

        if not np.all(np.isfinite([u_star_new, t_star_new, q_star_new])):
            return [np.nan, np.nan, np.nan, np.nan, 1]
        if u_star_new <= 0:
            return [np.nan, np.nan, np.nan, np.nan, 5]

        T_ref = float(np.nanmean(T_v))
        q_ref = float(np.nanmean(q_v))
        theta_v_ref = T_ref * (1.0 + 0.61 * q_ref)
        theta_v_star = t_star_new + 0.61 * T_ref * q_star_new

        if abs(theta_v_star) < cfg.min_abs_tv_star:
            L_new = np.sign(L) * cfg.max_abs_L_m
        else:
            L_new = (theta_v_ref * u_star_new**2) / (KAPPA * G * theta_v_star)

        if not np.isfinite(L_new):
            return [np.nan, np.nan, np.nan, np.nan, 1]
        L_new = float(np.clip(L_new, -cfg.max_abs_L_m, cfg.max_abs_L_m))

        abs_diff_L = abs(L_new - L)
        rel_diff_L = abs_diff_L / max(abs(L), 1.0)

        u_star, t_star, q_star, L = u_star_new, t_star_new, q_star_new, L_new

        if (abs_diff_L < cfg.most_tolerance_L_m) or (rel_diff_L < cfg.most_relative_tolerance):
            converged = True
            break

    if not converged:
        return [np.nan, np.nan, np.nan, np.nan, 6]

    T_ref = float(np.nanmean(T_v))
    q_ref = float(np.nanmean(q_v))
    rho = air_density_moist(P, T_ref, q_ref) if cfg.use_moist_air_density else air_density_dry(P, T_ref)
    Lv = latent_heat_vaporization(T_ref)
    if not np.isfinite(rho) or not np.isfinite(Lv):
        return [np.nan, np.nan, np.nan, np.nan, 7]

    QH = -rho * CP * u_star * t_star
    QE = -rho * Lv * u_star * q_star
    return [float(u_star), float(QH), float(QE), float(L), 0]


