def apply_post_qc_flux_outputs(
    df_input: pd.DataFrame,
    suffix: str,
    cfg,
    stability_col: Optional[str] = None,
    stability_range: Optional[Tuple[float, float]] = None,
) -> pd.DataFrame:
    """
    Apply post-QC to MOST or BRN_ANC flux outputs.

    Separates:
    - Status_*   : method execution status.
    - QC_Flag_*  : physical plausibility flag of the final output.

    QC flags:
    0 = PASS
    1 = USTAR_OUT_OF_RANGE
    2 = SENSIBLE_HEAT_FLUX_OUT_OF_RANGE
    3 = LATENT_HEAT_FLUX_OUT_OF_RANGE
    4 = STABILITY_PARAMETER_OUT_OF_RANGE
    5 = METHOD_STATUS_NOT_PASS
    6 = MISSING_METHOD_OUTPUT
    7 = NONFINITE_METHOD_OUTPUT
    9 = UNEXPECTED_NUMERICAL_ERROR
    """

    res = df_input.copy()

    # -------------------------------------------------------------------------
    # 1. Column names
    # -------------------------------------------------------------------------
    u_col = f"u_star{suffix}"
    qh_col = f"QH_Wm2{suffix}"
    qe_col = f"QE_Wm2{suffix}"
    flag_col = f"QC_Flag{suffix}"
    status_col = f"Status{suffix}"   # <-- ESTA LÍNEA RESUELVE EL NameError

    # Raw output columns
    u_raw_col = f"{u_col}_raw"
    qh_raw_col = f"{qh_col}_raw"
    qe_raw_col = f"{qe_col}_raw"

    # -------------------------------------------------------------------------
    # 2. Preserve raw outputs before final masking
    # -------------------------------------------------------------------------
    preserve_raw = getattr(cfg, "preserve_raw_outputs", True)

    if preserve_raw:
        if u_col in res.columns:
            res[u_raw_col] = res[u_col]
        if qh_col in res.columns:
            res[qh_raw_col] = res[qh_col]
        if qe_col in res.columns:
            res[qe_raw_col] = res[qe_col]

    # -------------------------------------------------------------------------
    # 3. Initialize QC flag
    # -------------------------------------------------------------------------
    res[flag_col] = 0

    # -------------------------------------------------------------------------
    # 4. Required output columns
    # -------------------------------------------------------------------------
    required_output_cols = [u_col, qh_col, qe_col]
    missing_required_cols = [c for c in required_output_cols if c not in res.columns]

    if missing_required_cols:
        res[flag_col] = 6
        return res

    # -------------------------------------------------------------------------
    # 5. Method status check
    # -------------------------------------------------------------------------
    # If Status_* exists and is not PASS, classify as METHOD_STATUS_NOT_PASS.
    # Do not use QC_Flag = 9 here.
    if status_col in res.columns:
        status_not_pass = res[status_col].fillna(9).astype(int) != 0
        res.loc[status_not_pass, flag_col] = 5

    # -------------------------------------------------------------------------
    # 6. Missing output check
    # -------------------------------------------------------------------------
    missing_output = (
        res[u_col].isna() |
        res[qh_col].isna() |
        res[qe_col].isna()
    )

    res.loc[
        (res[flag_col] == 0) & missing_output,
        flag_col
    ] = 6

    # -------------------------------------------------------------------------
    # 7. Non-finite output check
    # -------------------------------------------------------------------------
    nonfinite_output = (
        ~np.isfinite(res[u_col]) |
        ~np.isfinite(res[qh_col]) |
        ~np.isfinite(res[qe_col])
    )

    res.loc[
        (res[flag_col] == 0) & nonfinite_output,
        flag_col
    ] = 7

    # -------------------------------------------------------------------------
    # 8. u_star range check
    # -------------------------------------------------------------------------
    u_low, u_high = cfg.ustar_range_ms

    bad_u = (
        ((res[u_col] < u_low) | (res[u_col] > u_high)) &
        (res[flag_col] == 0)
    )

    res.loc[bad_u, flag_col] = 1

    # -------------------------------------------------------------------------
    # 9. QH range check
    # -------------------------------------------------------------------------
    qh_low, qh_high = cfg.QH_range_Wm2

    bad_qh = (
        ((res[qh_col] < qh_low) | (res[qh_col] > qh_high)) &
        (res[flag_col] == 0)
    )

    res.loc[bad_qh, flag_col] = 2

    # -------------------------------------------------------------------------
    # 10. QE range check
    # -------------------------------------------------------------------------
    qe_low, qe_high = cfg.QE_range_Wm2

    bad_qe = (
        ((res[qe_col] < qe_low) | (res[qe_col] > qe_high)) &
        (res[flag_col] == 0)
    )

    res.loc[bad_qe, flag_col] = 3

    # -------------------------------------------------------------------------
    # 11. Stability range check
    # -------------------------------------------------------------------------
    if stability_col is not None and stability_range is not None:
        if stability_col in res.columns:
            s_low, s_high = stability_range

            bad_stability = (
                ((res[stability_col] < s_low) | (res[stability_col] > s_high)) &
                (res[flag_col] == 0)
            )

            res.loc[bad_stability, flag_col] = 4

    # -------------------------------------------------------------------------
    # 12. Convert flag type
    # -------------------------------------------------------------------------
    res[flag_col] = res[flag_col].astype("int16")

    # -------------------------------------------------------------------------
    # 13. Mask invalid final outputs
    # -------------------------------------------------------------------------
    # Raw values remain stored in *_raw columns.
    res.loc[
        res[flag_col] != 0,
        [u_col, qh_col, qe_col]
    ] = np.nan

    return res


