def plot_diurnal_flux_cycle(final_df: pd.DataFrame, out_dir: str, *, title_prefix: str = "") -> None:
    set_common_plot_style()
    os.makedirs(out_dir, exist_ok=True)
    df = standardize_flux_column_names(final_df.copy())
    df["minute_of_day"] = df.index.hour * 60 + df.index.minute
    variables = [
        ("QH_Wm2_MOST", "QH_Wm2_BRN_ANC", "Sensible Heat Flux", "QH (W m$^{-2}$)", "diurnal_QH"),
        ("QE_Wm2_MOST", "QE_Wm2_BRN_ANC", "Latent Heat Flux", "QE (W m$^{-2}$)", "diurnal_QE"),
        ("u_star_MOST", "u_star_BRN_ANC", "Friction Velocity", "$u_*$ (m s$^{-1}$)", "diurnal_ustar"),
    ]
    for col_most, col_brn, title, ylabel, filename in variables:
        if col_most not in df.columns or col_brn not in df.columns:
            continue
        grp = df.groupby("minute_of_day")[[col_most, col_brn]]
        mean = grp.mean()
        std = grp.std()
        hours = mean.index.to_numpy(dtype=float) / 60.0
        fig, ax = plt.subplots(figsize=(9, 5))
        for col, label, color, linestyle in [
            (col_most, "MOST", PLOT_COLORS["MOST"], "-"),
            (col_brn, "BRN anchored", PLOT_COLORS["BRN_ANC"], "--"),
        ]:
            ax.plot(hours, mean[col], color=color, linestyle=linestyle, label=label)
            ax.fill_between(hours, mean[col] - std[col], mean[col] + std[col], color=color, alpha=0.15)
        ax.axhline(0, color="0.3", linewidth=1.0, alpha=0.7)
        ax.set_title(f"{title_prefix}Mean Diurnal Cycle - {title}", fontweight="bold")
        ax.set_xlabel("Local time (hour)")
        ax.set_ylabel(ylabel)
        ax.set_xlim(-0.1, 24.0)
        ax.set_xticks(np.arange(0, 25, 2))
        ax.grid(True)
        ax.legend(frameon=True)
        plt.tight_layout()
        fig.savefig(os.path.join(out_dir, f"{filename}.png"), bbox_inches="tight")
        fig.savefig(os.path.join(out_dir, f"{filename}.pdf"), bbox_inches="tight")
        plt.close(fig)


