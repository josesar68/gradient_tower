def convert_index_utc_to_local(
    df: Optional[pd.DataFrame],
    local_tz: str = DEFAULT_LOCAL_TZ,
    remove_timezone: bool = True,
) -> Optional[pd.DataFrame]:
    """Convert a DataFrame DateTimeIndex from UTC to a local time zone."""
    if df is None:
        return None
    if df.empty:
        return df.copy()

    out = df.copy()
    out.index = pd.to_datetime(out.index)

    if out.index.tz is None:
        out.index = out.index.tz_localize("UTC")
    else:
        out.index = out.index.tz_convert("UTC")

    out.index = out.index.tz_convert(local_tz)

    if remove_timezone:
        out.index = out.index.tz_localize(None)

    out.index.name = "time"
    return out


def _empty_time_dataframe(ds: xr.Dataset) -> pd.DataFrame:
    if "time" not in ds:
        raise KeyError("Dataset does not contain a 'time' coordinate/variable.")
    return pd.DataFrame(index=pd.to_datetime(ds["time"].values))


def extract_2d_variable_to_original_columns(
    ds: xr.Dataset,
    var_name: str,
    col_map: Mapping[float, str],
    *,
    nearest_tolerance_m: float = 1.0e-6,
) -> pd.DataFrame:
    """Extract a time-height xarray variable and rebuild original tower columns."""
    if var_name not in ds:
        out = _empty_time_dataframe(ds)
        out.index.name = "time"
        return out

    da = ds[var_name]
    required_dims = {"time", "height"}
    if not required_dims.issubset(set(da.dims)):
        raise ValueError(f"Variable '{var_name}' must have time-height dimensions. Found: {da.dims}")
    if "height" not in da.coords:
        raise ValueError(f"Variable '{var_name}' has a height dimension but no height coordinate.")

    out = _empty_time_dataframe(ds)
    available_heights = np.asarray(da["height"].values, dtype=float)

    for height, original_col in col_map.items():
        h = float(height)
        if np.any(np.isclose(available_heights, h, atol=nearest_tolerance_m, rtol=0.0)):
            matched_height = float(available_heights[np.argmin(np.abs(available_heights - h))])
            out[original_col] = da.sel(height=matched_height).to_pandas().to_numpy()
        else:
            warnings.warn(
                f"Height {h:g} m for variable '{var_name}' was not found in NetCDF. "
                f"Column '{original_col}' was omitted.",
                RuntimeWarning,
            )

    out.index.name = "time"
    return out


def extract_derived_variable_by_height(ds: xr.Dataset, var_name: str) -> pd.DataFrame:
    """Extract derived time-height variables such as q and theta_v as var_height columns."""
    if var_name not in ds:
        out = _empty_time_dataframe(ds)
        out.index.name = "time"
        return out

    da = ds[var_name]
    if not {"time", "height"}.issubset(set(da.dims)):
        raise ValueError(f"Variable '{var_name}' must have time-height dimensions. Found: {da.dims}")
    if "height" not in da.coords:
        raise ValueError(f"Variable '{var_name}' has a height dimension but no height coordinate.")

    out = _empty_time_dataframe(ds)
    for height in np.asarray(da["height"].values, dtype=float):
        col = f"{var_name}_{int(height)}" if float(height).is_integer() else f"{var_name}_{height:g}"
        out[col] = da.sel(height=height).to_pandas().to_numpy()

    out.index.name = "time"
    return out


def extract_qc_flags_to_original_columns(
    ds: xr.Dataset,
    qc_var_name: str,
    col_map: Mapping[float, str],
) -> pd.DataFrame:
    """Extract QC flags and preserve original column names."""
    df = extract_2d_variable_to_original_columns(ds, qc_var_name, col_map)
    for col in df.columns:
        df[col] = df[col].fillna(1).astype("int32")
    return df


def safe_concat_dataframes(parts: Sequence[pd.DataFrame], fallback_index: pd.Index) -> pd.DataFrame:
    """Concatenate non-empty DataFrames; return an empty DataFrame with fallback_index otherwise."""
    valid = [df for df in parts if df is not None and not df.empty]
    if valid:
        out = pd.concat(valid, axis=1)
    else:
        out = pd.DataFrame(index=fallback_index.copy())
    out.index.name = "time"
    return out


def read_saved_tower_dataframes_from_netcdf(
    nc_file: str = DEFAULT_NC_FILE,
    *,
    convert_to_local: bool = True,
    local_tz: str = DEFAULT_LOCAL_TZ,
    remove_timezone: bool = True,
    engine: str = "netcdf4",
) -> Tuple[pd.DataFrame, pd.DataFrame, Optional[pd.DataFrame], xr.Dataset, Optional[xr.Dataset]]:
    """Read cleaned, flags and raw DataFrames from an OGHYO tower NetCDF file."""
    if not os.path.exists(nc_file):
        raise FileNotFoundError(f"NetCDF file does not exist: {nc_file}")

    ds = xr.open_dataset(nc_file, engine=engine, decode_times=True)

    try:
        ds_raw = xr.open_dataset(nc_file, group="raw_uncontrolled", engine=engine, decode_times=True)
    except (OSError, ValueError, KeyError) as exc:
        warnings.warn(f"Group 'raw_uncontrolled' could not be opened: {exc}", RuntimeWarning)
        ds_raw = None

    fallback_index = pd.to_datetime(ds["time"].values)

    df_ta = extract_2d_variable_to_original_columns(ds, "ta", DEFAULT_TEMP_COLS)
    df_rh = extract_2d_variable_to_original_columns(ds, "hur", DEFAULT_RH_COLS)
    df_ws = extract_2d_variable_to_original_columns(ds, "ws", DEFAULT_WIND_COLS)
    df_wd = extract_2d_variable_to_original_columns(ds, "wd", DEFAULT_WDIR_COLS)
    df_q = extract_derived_variable_by_height(ds, "q")
    df_theta_v = extract_derived_variable_by_height(ds, "theta_v")

    cleaned = safe_concat_dataframes(
        [df_ta, df_rh, df_ws, df_wd, df_q, df_theta_v],
        fallback_index=fallback_index,
    )

    if "P_Pa" in ds:
        cleaned["P_Pa"] = ds["P_Pa"].to_pandas().to_numpy()

    flag_ta = extract_qc_flags_to_original_columns(ds, "ta_qc_flags", DEFAULT_TEMP_COLS)
    flag_rh = extract_qc_flags_to_original_columns(ds, "hur_qc_flags", DEFAULT_RH_COLS)
    flag_ws = extract_qc_flags_to_original_columns(ds, "ws_qc_flags", DEFAULT_WIND_COLS)
    flags = safe_concat_dataframes([flag_ta, flag_rh, flag_ws], fallback_index=fallback_index)

    raw: Optional[pd.DataFrame]
    if ds_raw is not None:
        raw = ds_raw.to_dataframe().dropna(axis=1, how="all")
        if isinstance(raw.index, pd.MultiIndex):
            if "time" in raw.index.names:
                raw = raw.reset_index().set_index("time")
            else:
                raise ValueError("raw_uncontrolled group has a MultiIndex without a 'time' level.")
        raw.index = pd.to_datetime(raw.index)
        raw.index.name = "time"
    else:
        raw = None

    if convert_to_local:
        cleaned = convert_index_utc_to_local(cleaned, local_tz=local_tz, remove_timezone=remove_timezone)
        flags = convert_index_utc_to_local(flags, local_tz=local_tz, remove_timezone=remove_timezone)
        raw = convert_index_utc_to_local(raw, local_tz=local_tz, remove_timezone=remove_timezone)

    assert cleaned is not None
    assert flags is not None
    return cleaned, flags, raw, ds, ds_raw


