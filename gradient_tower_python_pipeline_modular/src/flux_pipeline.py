# 6. NETCDF ENCODING
# =============================================================================

def build_netcdf_encoding(
    ds: xr.Dataset,
    *,
    time_name: str = "time",
    zlib: bool = True,
    complevel: int = 4,
    float_dtype: str = "float32",
) -> Dict[str, Dict[str, Any]]:
    """
    Build NetCDF encoding dictionary.

    Numeric floating variables are compressed and stored as float32 by default.
    Integer QC/status variables are compressed but keep their integer type.
    String variables are left without compression to avoid backend issues.
    """

    encoding: Dict[str, Dict[str, Any]] = {}

    for var in ds.data_vars:
        dtype = ds[var].dtype

        if np.issubdtype(dtype, np.floating):
            encoding[var] = {
                "zlib": zlib,
                "complevel": complevel,
                "dtype": float_dtype,
                "_FillValue": np.nan,
            }

        elif np.issubdtype(dtype, np.integer):
            info = np.iinfo(dtype)
            fill_value = -1 if info.min <= -1 <= info.max else info.max
            encoding[var] = {
                "zlib": zlib,
                "complevel": complevel,
                "_FillValue": dtype.type(fill_value),
            }

        else:
            # String/object variables: safest option is no compression encoding
            encoding[var] = {}

    if time_name in ds.coords:
        encoding[time_name] = {
            "units": "seconds since 1970-01-01 00:00:00",
            "calendar": "standard",
        }

    return encoding

def append_audit_tables_to_netcdf(
    output_nc: Path,
    report: Dict[str, Any],
    *,
    engine: str = "netcdf4",
) -> None:
    """
    Append audit tables as auxiliary NetCDF groups.
    """

    import xarray as xr

    audit_keys = [
        "summary",
        "paired_comparison",
        "status_vs_qc_audit",
        "sign_consistency_audit",
        "extreme_flux_audit",
        "hourly_paired_audit",
    ]

    for key in audit_keys:

        if key not in report:
            continue

        table = report[key]

        if table is None:
            continue

        try:

            # ----------------------------------------------------------
            # Series -> DataFrame
            # ----------------------------------------------------------
            if isinstance(table, pd.Series):
                table = table.to_frame(name="value")

            if not isinstance(table, pd.DataFrame):
                continue

            table = table.copy()

            # ----------------------------------------------------------
            # Flatten multi-index safely
            # ----------------------------------------------------------
            if isinstance(table.index, pd.MultiIndex):
                table = table.reset_index()

            # ----------------------------------------------------------
            # Convert objects to string
            # ----------------------------------------------------------
            for col in table.columns:

                if pd.api.types.is_object_dtype(table[col]):
                    table[col] = table[col].astype(str)

            ds_aux = xr.Dataset.from_dataframe(table)

            ds_aux.attrs["audit_table"] = key

            ds_aux.to_netcdf(
                output_nc,
                mode="a",
                group=f"audit/{key}",
                engine=engine,
            )

        except Exception as exc:

            print(f"WARNING: could not append audit table '{key}': {exc}")


