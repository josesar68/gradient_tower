def _temperature_series_to_kelvin(s: pd.Series) -> pd.Series:
    """Return temperature in K; accepts either Celsius-like or Kelvin-like inputs."""
    out = pd.to_numeric(s, errors="coerce")
    med = np.nanmedian(out.to_numpy(dtype=float)) if len(out) else np.nan
    if np.isfinite(med) and med < 150.0:
        return out + 273.15
    return out


