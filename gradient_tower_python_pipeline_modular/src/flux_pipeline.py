def validate_30min_flux_dataframe(
    final_df_30m: pd.DataFrame,
    *,
    expected_freq: str = "30min",
    require_datetime_index: bool = True,
    allow_duplicate_times: bool = False,
) -> pd.DataFrame:
    """
    Audit the 30-min flux DataFrame before saving to NetCDF.

    Returns
    -------
    audit : pd.DataFrame
        Structured validation report.
    """

    records = []

    def add(check: str, status: str, detail: str) -> None:
        records.append({
            "check": check,
            "status": status,
            "detail": detail,
        })

    if final_df_30m is None:
        raise ValueError("final_df_30m is None.")

    if final_df_30m.empty:
        raise ValueError("final_df_30m is empty.")

    # -------------------------------------------------------------------------
    # Index checks
    # -------------------------------------------------------------------------
    is_datetime = isinstance(final_df_30m.index, pd.DatetimeIndex)

    if require_datetime_index and not is_datetime:
        raise TypeError("final_df_30m must have a pandas DatetimeIndex.")

    add(
        "datetime_index",
        "PASS" if is_datetime else "WARN",
        f"type={type(final_df_30m.index).__name__}",
    )

    if is_datetime:
        add(
            "time_range",
            "INFO",
            f"{final_df_30m.index.min()} -> {final_df_30m.index.max()}",
        )

        is_sorted = final_df_30m.index.is_monotonic_increasing
        add(
            "index_monotonic",
            "PASS" if is_sorted else "WARN",
            "Index is sorted increasing" if is_sorted else "Index is not sorted increasing",
        )

        n_duplicates = int(final_df_30m.index.duplicated().sum())

        if n_duplicates > 0 and not allow_duplicate_times:
            add(
                "duplicate_timestamps",
                "FAIL",
                f"duplicated={n_duplicates}",
            )
        else:
            add(
                "duplicate_timestamps",
                "PASS" if n_duplicates == 0 else "WARN",
                f"duplicated={n_duplicates}",
            )

        inferred_freq = pd.infer_freq(final_df_30m.index)

        add(
            "inferred_frequency",
            "PASS" if inferred_freq is not None else "WARN",
            f"inferred_freq={inferred_freq}, expected={expected_freq}",
        )

    # -------------------------------------------------------------------------
    # Column checks
    # -------------------------------------------------------------------------
    add(
        "n_rows_columns",
        "INFO",
        f"rows={len(final_df_30m)}, columns={len(final_df_30m.columns)}",
    )

    qh_cols = [c for c in final_df_30m.columns if str(c).startswith("QH")]
    qe_cols = [c for c in final_df_30m.columns if str(c).startswith("QE")]
    qc_cols = [
        c for c in final_df_30m.columns
        if any(token in str(c).lower() for token in ["qc", "flag", "status"])
    ]

    add(
        "QH_columns",
        "PASS" if qh_cols else "WARN",
        f"{qh_cols}",
    )

    add(
        "QE_columns",
        "PASS" if qe_cols else "WARN",
        f"{qe_cols}",
    )

    add(
        "QC_status_flag_columns",
        "PASS" if qc_cols else "WARN",
        f"n={len(qc_cols)}; columns={qc_cols}",
    )

    return pd.DataFrame(records)


