def paired_method_comparison(
    final_df: pd.DataFrame,
    x_col: str,
    y_col: str,
) -> Dict[str, float]:
    """
    Compare BRN_ANC against MOST for paired valid records.
    """
    valid = (
        final_df[x_col].notna() &
        final_df[y_col].notna() &
        np.isfinite(final_df[x_col]) &
        np.isfinite(final_df[y_col])
    )

    x = final_df.loc[valid, x_col].astype(float).values
    y = final_df.loc[valid, y_col].astype(float).values

    if len(x) < 10:
        return {
            "n": len(x),
            "slope": np.nan,
            "intercept": np.nan,
            "r2": np.nan,
            "pearson_r": np.nan,
            "rmse": np.nan,
            "mae": np.nan,
            "mbe": np.nan,
        }

    slope, intercept = np.polyfit(x, y, 1)
    r = np.corrcoef(x, y)[0, 1]

    return {
        "n": int(len(x)),
        "slope": float(slope),
        "intercept": float(intercept),
        "r2": float(r**2),
        "pearson_r": float(r),
        "rmse": float(np.sqrt(np.mean((y - x) ** 2))),
        "mae": float(np.mean(np.abs(y - x))),
        "mbe": float(np.mean(y - x)),
    }


def build_paired_comparison_table(final_df: pd.DataFrame) -> pd.DataFrame:
    rows = []

    pairs = {
        "u_star": ("u_star_MOST", "u_star_BRN_ANC"),
        "QH_Wm2": ("QH_Wm2_MOST", "QH_Wm2_BRN_ANC"),
        "QE_Wm2": ("QE_Wm2_MOST", "QE_Wm2_BRN_ANC"),
    }

    for variable, (most_col, brn_col) in pairs.items():
        metrics = paired_method_comparison(final_df, most_col, brn_col)
        metrics["variable"] = variable
        rows.append(metrics)

    return pd.DataFrame(rows).set_index("variable")

def build_hourly_paired_audit(final_df: pd.DataFrame) -> pd.DataFrame:
    """
    Hourly paired audit for MOST vs BRN_ANC using only records valid in both methods.
    """
    required = ["u_star_MOST", "u_star_BRN_ANC", "QH_Wm2_MOST", "QH_Wm2_BRN_ANC",
                "QE_Wm2_MOST", "QE_Wm2_BRN_ANC"]

    missing = [c for c in required if c not in final_df.columns]
    if missing:
        return pd.DataFrame()

    df = final_df.copy()
    paired = (
        df["u_star_MOST"].notna() &
        df["u_star_BRN_ANC"].notna() &
        df["QH_Wm2_MOST"].notna() &
        df["QH_Wm2_BRN_ANC"].notna() &
        df["QE_Wm2_MOST"].notna() &
        df["QE_Wm2_BRN_ANC"].notna()
    )

    df = df.loc[paired].copy()
    if df.empty:
        return pd.DataFrame()

    df["hour"] = df.index.hour + df.index.minute / 60.0

    df["ustar_diff"] = df["u_star_BRN_ANC"] - df["u_star_MOST"]
    df["QH_diff"] = df["QH_Wm2_BRN_ANC"] - df["QH_Wm2_MOST"]
    df["QE_diff"] = df["QE_Wm2_BRN_ANC"] - df["QE_Wm2_MOST"]

    return df.groupby("hour").agg(
        n=("u_star_MOST", "count"),
        ustar_MOST_mean=("u_star_MOST", "mean"),
        ustar_BRN_mean=("u_star_BRN_ANC", "mean"),
        ustar_diff_mean=("ustar_diff", "mean"),
        QH_MOST_mean=("QH_Wm2_MOST", "mean"),
        QH_BRN_mean=("QH_Wm2_BRN_ANC", "mean"),
        QH_diff_mean=("QH_diff", "mean"),
        QE_MOST_mean=("QE_Wm2_MOST", "mean"),
        QE_BRN_mean=("QE_Wm2_BRN_ANC", "mean"),
        QE_diff_mean=("QE_diff", "mean"),
        Ri_b_median=("Ri_b_BRN_ANC", "median") if "Ri_b_BRN_ANC" in df.columns else ("u_star_MOST", "count"),
        L_MOST_median=("L_MOST", "median") if "L_MOST" in df.columns else ("u_star_MOST", "count"),
    )

def audit_flux_sign_consistency(final_df: pd.DataFrame, cfg: Flux30MinConfig) -> pd.Series:
    """
    Check sign consistency between scalar gradients and fluxes.

    Expected:
    - QH > 0 when T_bottom > T_top, i.e. dT = T_top - T_bottom < 0.
    - QE > 0 when q_bottom > q_top, i.e. dq = q_top - q_bottom < 0.
    """
    bottom_z = min(cfg.heights_m)
    top_z = max(cfg.heights_m)

    temp_bottom = cfg.temp_cols[bottom_z]
    temp_top = cfg.temp_cols[top_z]
    q_bottom = cfg.q_cols[bottom_z]
    q_top = cfg.q_cols[top_z]

    dT = final_df[temp_top] - final_df[temp_bottom]
    dq = final_df[q_top] - final_df[q_bottom]

    out = {}

    for method in ["MOST", "BRN_ANC"]:
        qh_col = f"QH_Wm2_{method}"
        qe_col = f"QE_Wm2_{method}"

        if qh_col in final_df.columns:
            valid = final_df[qh_col].notna() & dT.notna()
            if valid.sum() > 0:
                mismatch = np.sign(final_df.loc[valid, qh_col]) == np.sign(dT.loc[valid])
                out[f"{method}_QH_sign_mismatch_pct"] = 100.0 * mismatch.mean()

        if qe_col in final_df.columns:
            valid = final_df[qe_col].notna() & dq.notna()
            if valid.sum() > 0:
                mismatch = np.sign(final_df.loc[valid, qe_col]) == np.sign(dq.loc[valid])
                out[f"{method}_QE_sign_mismatch_pct"] = 100.0 * mismatch.mean()

    return pd.Series(out)

def audit_extreme_fluxes(final_df: pd.DataFrame) -> pd.DataFrame:
    checks = {}

    if "QE_Wm2_MOST" in final_df:
        checks["QE_MOST_gt_500"] = final_df["QE_Wm2_MOST"] > 500
    if "QE_Wm2_BRN_ANC" in final_df:
        checks["QE_BRN_gt_500"] = final_df["QE_Wm2_BRN_ANC"] > 500
    if "QH_Wm2_MOST" in final_df:
        checks["QH_MOST_gt_400"] = final_df["QH_Wm2_MOST"] > 400
    if "QH_Wm2_BRN_ANC" in final_df:
        checks["QH_BRN_gt_400"] = final_df["QH_Wm2_BRN_ANC"] > 400
    if "QH_Wm2_MOST" in final_df:
        checks["QH_MOST_lt_minus100"] = final_df["QH_Wm2_MOST"] < -100
    if "QH_Wm2_BRN_ANC" in final_df:
        checks["QH_BRN_lt_minus100"] = final_df["QH_Wm2_BRN_ANC"] < -100
    if "u_star_MOST" in final_df:
        checks["USTAR_MOST_gt_1"] = final_df["u_star_MOST"] > 1.0
    if "u_star_BRN_ANC" in final_df:
        checks["USTAR_BRN_gt_1"] = final_df["u_star_BRN_ANC"] > 1.0

    rows = []
    for name, mask in checks.items():
        rows.append({
            "check": name,
            "count": int(mask.sum()),
            "pct_total": 100.0 * mask.mean(),
        })

    return pd.DataFrame(rows)


