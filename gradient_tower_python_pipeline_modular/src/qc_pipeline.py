def expected_input_columns(cfg: TowerConfig) -> List[str]:
    """Return all sensor columns expected by the QC pipeline."""
    varmaps = [cfg.temp_cols, cfg.rh_cols, cfg.wind_cols, cfg.wdir_cols]
