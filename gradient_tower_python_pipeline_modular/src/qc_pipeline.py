def run_full_qc_pipeline(
    temp_calib_file: str | Path = TEMP_CALIB_FILE,
    rh_calib_file: str | Path = RH_CALIB_FILE,
    tower_mat_file: str | Path = TOWER_MAT_FILE,
    sun_mat_file: str | Path = SUN_MAT_FILE,
    output_netcdf: str | Path = OUTPUT_NETCDF,
    cfg: Optional[TowerConfig] = None,
    export_netcdf: bool = True,
    global_attrs: Optional[Dict[str, object]] = None,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Run the complete optimized QC workflow.

    Returns
    -------
    raw_prepared : pandas.DataFrame
        Calibrated and time-indexed input data before QC.
    cleaned : pandas.DataFrame
        Cleaned data with derived variables.
    flags : pandas.DataFrame
        Bitmask QC flags.
    summary : pandas.DataFrame
        QC summary by variable.
    missing_summary : pandas.DataFrame
        NaN summary before QC.
    """
    if cfg is None:
        cfg = TowerConfig(strict_columns=STRICT_COLUMNS)

    temp_param = read_calibration_matrix(temp_calib_file, n_sensors=6)
    rh_param = read_calibration_matrix(rh_calib_file, n_sensors=6)
    temp_cal = calibration_dict(temp_param, prefix="temp_n", n_sensors=6)
    rh_cal = calibration_dict(rh_param, prefix="RH_n", n_sensors=6)

    tower_mat = load_mat_file(tower_mat_file)
    sun_mat = load_mat_file(sun_mat_file)

    raw_df = build_tower_dataframe_from_mat(tower_mat, sun_mat, temp_cal, rh_cal)
    raw_prepared = add_datetime_and_sunrise(
        raw_df,
        timezone=cfg.timezone,
        site_name=SITE_NAME,
        site_region=SITE_REGION,
        latitude=SITE_LAT,
        longitude=SITE_LON,
        duplicate_policy=cfg.duplicate_policy,
    )

    missing_summary = summarize_missing_values(raw_prepared)
    cleaned, flags, summary = preprocess_tower(raw_prepared, cfg)

    if export_netcdf:
        if global_attrs is None:
            global_attrs = {
                "title": "Surface Boundary Layer Observations - Mantaro Valley",
                "institution": "Instituto Geofísico del Perú (IGP)",
                "references": "https://doi.org/10.1016/j.agrformet.2025.110570",
                "creator_name": "Dr. José Luis Flores Rojas",
                "comment": "1-minute averaged data from the ACNS project tower.",
                "description": "Full dataset including raw uncontrolled values, cleaned values and QC bitmask flags.",
            }
        save_tower_data_to_netcdf(
            cleaned_df=cleaned,
            flags_df=flags,
            config=cfg,
            output_filename=output_netcdf,
            raw_df=raw_prepared,
            global_attrs=global_attrs,
        )

    return raw_prepared, cleaned, flags, summary, missing_summary

