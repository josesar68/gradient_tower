def preprocess_tower(df: pd.DataFrame, cfg: TowerConfig) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Main QC preprocessing pipeline.

    Returns
    -------
    cleaned : pandas.DataFrame
        Cleaned data with diagnostic and derived columns.
    flags : pandas.DataFrame
        Integer QC bitmask per original variable column.
    summary : pandas.DataFrame
        Summary counts by variable column.
    """
    cleaned = fix_index_and_tz(
        df.copy(),
        tz_local=cfg.timezone,
        naive_are_local=cfg.naive_are_local,
        duplicate_policy=cfg.duplicate_policy,
    )

    inferred_sample_period_s = cfg.sample_period_s or infer_sample_period_s(cleaned.index)

    if cfg.target_freq is not None:
        original_index = cleaned.index.copy()
        cleaned = cleaned.asfreq(cfg.target_freq)
        resample_mask = pd.Series(~cleaned.index.isin(original_index), index=cleaned.index)
    else:
        resample_mask = pd.Series(False, index=cleaned.index)

    cleaned["time_utc"] = cleaned.index.tz_convert("UTC")

    if "dir_wind" in cleaned.columns:
        cleaned["dir_wind"] = pd.to_numeric(cleaned["dir_wind"], errors="coerce") % 360.0

    varmaps = {
        "temp": cfg.temp_cols,
        "rh": cfg.rh_cols,
        "wind": cfg.wind_cols,
        "wdir": cfg.wdir_cols if cfg.wdir_cols else {},
    }

    all_cols = expected_input_columns(cfg)
    missing_cols = [col for col in all_cols if col not in cleaned.columns]
    if missing_cols and cfg.strict_columns:
        raise KeyError(f"Columnas requeridas faltantes para QC: {missing_cols}")
    for col in missing_cols:
        cleaned[col] = np.nan

    for col in all_cols:
        cleaned[col] = pd.to_numeric(cleaned[col], errors="coerce")

    flags = pd.DataFrame(0, index=cleaned.index, columns=all_cols, dtype="int32")
    spike_severity_cols: Dict[str, pd.Series] = {}

    for vtype, mapping in varmaps.items():
        rng = cfg.ranges[vtype]
        step_lim = cfg.step_limits[vtype]
        eps = cfg.persistence_eps[vtype]
        k = cfg.mad_k_by_var[vtype]
        zero_mad_dev = cfg.zero_mad_min_dev[vtype]

        for z, col in mapping.items():
            s = cleaned[col].astype(float)

            missing_fail = s.isna()
            range_fail = apply_range_check(s, rng)
            step_fail = apply_step_check(s, step_lim, vtype, sample_period_s=inferred_sample_period_s)
            persist_fail = apply_persistence_check(s, eps, cfg.persistence_min_samples, vtype)
            spike_fail, spike_severity = apply_spike_mad_check(s, cfg.mad_window, k, vtype, zero_mad_dev)

            set_flag(flags, col, missing_fail, BIT_MISSING)
            set_flag(flags, col, range_fail, BIT_RANGE)
            set_flag(flags, col, step_fail, BIT_STEP)
            set_flag(flags, col, persist_fail, BIT_PERSIST)
            set_flag(flags, col, spike_fail, BIT_SPIKE)

            if vtype == "wind":
                calm_fail = (s < cfg.calm_ws_ms) & s.notna()
                set_flag(flags, col, calm_fail, BIT_CALM)

            inconsist_fail = pd.Series(False, index=cleaned.index)
            if vtype == "rh":
                tcol = cfg.temp_cols.get(z)
                if tcol is not None and tcol in cleaned.columns:
                    inconsist_fail = rh_internal_consistency(cleaned[tcol].astype(float), s)
                    set_flag(flags, col, inconsist_fail, BIT_INCONSIST)

            if cfg.target_freq is not None:
                set_flag(flags, col, resample_mask, BIT_RESAMPLE)

            spike_severity_cols[f"{col}_spike_severity"] = spike_severity

            # Hard-fail policy: RANGE always; STEP and SPIKE only when simultaneous.
            hard_mask = pd.Series(False, index=cleaned.index)
            if BIT_RANGE in cfg.hard_fail_bits:
                hard_mask |= range_fail
            if (BIT_STEP in cfg.hard_fail_bits) and (BIT_SPIKE in cfg.hard_fail_bits):
                hard_mask |= (step_fail & spike_fail)
            elif BIT_STEP in cfg.hard_fail_bits:
                hard_mask |= step_fail
            elif BIT_SPIKE in cfg.hard_fail_bits:
                hard_mask |= spike_fail

            if cfg.remove_persistence and BIT_PERSIST in cfg.hard_fail_bits:
                hard_mask |= persist_fail
            if cfg.remove_rh_inconsistency and BIT_INCONSIST in cfg.hard_fail_bits and vtype == "rh":
                hard_mask |= inconsist_fail

            cleaned.loc[hard_mask, col] = np.nan

    for cname, sev in spike_severity_cols.items():
        cleaned[cname] = sev

    # Thermodynamic derived variables.
    P_site = hypsometric_pressure(cfg.site_altitude_m)
    cleaned["P_Pa"] = float(P_site)

    for z in cfg.heights_m:
        tcol = cfg.temp_cols.get(z)
        rhcol = cfg.rh_cols.get(z)
        if tcol in cleaned.columns and rhcol in cleaned.columns:
            T = cleaned[tcol].astype(float)
            RH = cleaned[rhcol].astype(float)
            RH_for_thermo = RH.clip(0, 100)
            e = (RH_for_thermo / 100.0) * es_tetens_pa(T.to_numpy(dtype=float))
            r = mixing_ratio(np.full(len(T), P_site, dtype=float), e)
            q = specific_humidity_from_r(r)
            theta_v = virtual_potential_temperature(
                T.to_numpy(dtype=float),
                q,
                np.full(len(T), P_site, dtype=float),
            )
            suffix = int(z) if float(z).is_integer() else str(z).replace(".", "p")
            cleaned[f"q_{suffix}"] = q
            cleaned[f"theta_v_{suffix}"] = theta_v

    def count_bits(x: pd.Series, bit: int) -> int:
        vals = x.astype("int64").to_numpy()
        return int(((vals & bit) > 0).sum())

    rows = []
    for col in all_cols:
        if col in cfg.temp_cols.values():
            vtype = "temp"
        elif col in cfg.rh_cols.values():
            vtype = "rh"
        elif col in cfg.wind_cols.values():
            vtype = "wind"
        elif col in cfg.wdir_cols.values():
            vtype = "wdir"
        else:
            vtype = "unknown"

        rows.append({
            "column": col,
            "variable_type": vtype,
            "n": len(flags),
            "missing": count_bits(flags[col], BIT_MISSING),
            "range": count_bits(flags[col], BIT_RANGE),
            "step": count_bits(flags[col], BIT_STEP),
            "persistence": count_bits(flags[col], BIT_PERSIST),
            "spike": count_bits(flags[col], BIT_SPIKE),
            "calm": count_bits(flags[col], BIT_CALM) if vtype == "wind" else 0,
            "inconsistency": count_bits(flags[col], BIT_INCONSIST) if vtype == "rh" else 0,
            "resample": count_bits(flags[col], BIT_RESAMPLE),
            "sample_period_s": inferred_sample_period_s,
            "mad_k_used": cfg.mad_k_by_var.get(vtype, np.nan),
            "hard_fail_policy": "RANGE or STEP&SPIKE; optional PERSIST/INCONSIST controlled by config",
            "removed_count": int(cleaned[col].isna().sum()),
        })

    summary = pd.DataFrame(rows).set_index("column")

    for path, obj in [
        (cfg.save_clean_csv, cleaned),
        (cfg.save_flags_csv, flags),
        (cfg.save_summary_csv, summary),
    ]:
        if path:
            ensure_parent_dir(path)
            obj.to_csv(path)

    for path, obj in [
        (cfg.save_clean_parquet, cleaned),
        (cfg.save_flags_parquet, flags),
        (cfg.save_summary_parquet, summary),
    ]:
        if path:
            ensure_parent_dir(path)
            obj.to_parquet(path)

    return cleaned, flags, summary


