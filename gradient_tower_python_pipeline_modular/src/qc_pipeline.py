def add_datetime_and_sunrise(
    df: pd.DataFrame,
    timezone: str = "America/Lima",
    site_name: str = "Huancayo",
    site_region: str = "Peru",
    latitude: float = -12.0,
    longitude: float = -75.3,
    duplicate_policy: str = "first",
) -> pd.DataFrame:
    """
    Add local Datetime index and sunrise time.

    The output keeps the same main variables as the original notebook but fixes
    duplicate handling by timestamp instead of whole-row duplication.
    """
    required_time_cols = ["year_tower", "month_tower", "day_tower", "hour_tower", "min_tower", "sec_tower"]
    missing = [c for c in required_time_cols if c not in df.columns]
    if missing:
        raise KeyError(f"Faltan columnas temporales: {missing}")

    out = df.copy()

    # Keep rows with valid time components only. Sensor NaNs are preserved for QC.
    out = out.dropna(subset=required_time_cols)

    dt_aux = out[required_time_cols].rename(
        columns={
            "year_tower": "year",
            "month_tower": "month",
            "day_tower": "day",
            "hour_tower": "hour",
            "min_tower": "minute",
            "sec_tower": "second",
        }
    )

    for col in dt_aux.columns:
        dt_aux[col] = pd.to_numeric(dt_aux[col], errors="coerce").astype("Int64")

    dt_local = pd.to_datetime(dt_aux, errors="coerce")
    valid_dt = dt_local.notna()
    if not valid_dt.all():
        warnings.warn(f"Se eliminarán {(~valid_dt).sum()} filas con fecha/hora inválida.")
        out = out.loc[valid_dt].copy()
        dt_local = dt_local.loc[valid_dt]

    dt_local = dt_local.dt.tz_localize(timezone)
    out["Datetime"] = dt_local

    location_info, sun_func = require_astral()
    city = location_info(site_name, site_region, timezone, latitude, longitude)
    days_local = dt_local.dt.date
    unique_days = pd.unique(days_local)

    sunrise_map = {}
    for d in unique_days:
        sunrise_map[d] = sun_func(city.observer, date=d, tzinfo=timezone)["sunrise"]

    out["sunrise"] = [sunrise_map[d].time() for d in days_local]

    out = out.set_index("Datetime").sort_index()

    if not out.index.is_unique:
        if duplicate_policy in {"first", "last"}:
            out = out[~out.index.duplicated(keep=duplicate_policy)]
        elif duplicate_policy in {"mean", "median"}:
            num = out.select_dtypes(include=[np.number]).groupby(level=0).agg(duplicate_policy)
            non = out.select_dtypes(exclude=[np.number]).groupby(level=0).first()
            out = pd.concat([num, non], axis=1).sort_index()
        else:
            raise ValueError("duplicate_policy debe ser first, last, mean o median.")

    out = out.drop(columns=required_time_cols, errors="ignore")

    # Normalize wind direction to [0, 360) while preserving NaN.
    if "dir_wind" in out.columns:
        out["dir_wind"] = pd.to_numeric(out["dir_wind"], errors="coerce") % 360.0

    return out


