def apply_range_check(s: pd.Series, rng: Tuple[float, float]) -> pd.Series:
    """Flag values outside [lo, hi]. NaN is handled by BIT_MISSING separately."""
    lo, hi = rng
    return ((s < lo) | (s > hi)).fillna(False)


def apply_step_check(
    s: pd.Series,
    max_step: Optional[float],
    vtype: str,
    sample_period_s: Optional[int] = None,
) -> pd.Series:
    """Flag excessive changes between consecutive samples."""
    if max_step is None:
        return pd.Series(False, index=s.index)

    if vtype == "wdir":
        diff = circular_abs_diff_deg(s.astype(float), s.astype(float).shift(1))
    else:
        diff = s.astype(float).diff().abs()

    fail = diff > max_step

    # Avoid flagging jumps across large temporal gaps when index is irregular.
    if isinstance(s.index, pd.DatetimeIndex) and sample_period_s is not None:
        dt = s.index.to_series().diff().dt.total_seconds()
        fail &= dt <= 1.5 * sample_period_s

    return fail.fillna(False)


def apply_persistence_check(s: pd.Series, eps: float, min_samples: int, vtype: str) -> pd.Series:
    """Flag periods with near-constant signal over a rolling window."""
    s_float = s.astype(float)
    if min_samples < 2:
        return pd.Series(False, index=s.index)

    if vtype == "wdir":
        center = rolling_circular_center_deg(s_float, min_samples, min_periods=min_samples)
        dev = circular_abs_diff_deg(s_float, center)
        roll_amp = dev.rolling(min_samples, center=True, min_periods=min_samples).max()
        flat = roll_amp <= eps
    else:
        roll_max = s_float.rolling(min_samples, center=True, min_periods=min_samples).max()
        roll_min = s_float.rolling(min_samples, center=True, min_periods=min_samples).min()
        flat = (roll_max - roll_min) <= eps

    return flat.fillna(False)


def apply_spike_mad_check(
    s: pd.Series,
    window: int,
    k: float,
    vtype: str,
    zero_mad_min_dev: float,
) -> Tuple[pd.Series, pd.Series]:
    """Robust spike detection using rolling median and MAD."""
    s_float = s.astype(float)
    valid = s_float.notna()

    if vtype == "wdir":
        center = rolling_circular_center_deg(s_float, window)
        mad = rolling_circular_mad_deg(s_float, window, center_deg=center)
        dev = circular_abs_diff_deg(s_float, center)
    else:
        center = rolling_median(s_float, window)
        mad = rolling_mad(s_float, window)
        dev = (s_float - center).abs()

    severity = pd.Series(np.nan, index=s.index, dtype=float)
    positive_mad = mad > 0
    severity.loc[positive_mad] = dev.loc[positive_mad] / mad.loc[positive_mad]

    fail = ((mad > 0) & (dev / mad > k))
    fail |= ((mad <= 0) & (dev > zero_mad_min_dev))
    fail &= valid

    return fail.fillna(False), severity


def rh_internal_consistency(temp_C: pd.Series, rh: pd.Series) -> pd.Series:
    """
    True where dew point exceeds air temperature.

    RH is not clipped here because out-of-range RH should remain physically visible.
    RANGE flags separately identify RH outside 0-100 %.
    """
    temp_arr = temp_C.to_numpy(dtype=float)
    rh_arr = rh.to_numpy(dtype=float)
    es = es_tetens_pa(temp_arr)
    e = (rh_arr / 100.0) * es

    with np.errstate(divide="ignore", invalid="ignore"):
        ln_ratio = np.log(e / 610.94)
        Td = 243.04 * ln_ratio / (17.625 - ln_ratio)

    out = pd.Series(Td, index=temp_C.index) > temp_C
    return out.fillna(False)


