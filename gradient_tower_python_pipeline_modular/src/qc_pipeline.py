def build_tower_dataframe_from_mat(
    tower_mat: dict,
    sun_mat: dict,
    temp_calib: Dict[str, Tuple[float, float]],
    rh_calib: Dict[str, Tuple[float, float]],
) -> pd.DataFrame:
    """
    Build the calibrated tower DataFrame from MATLAB dictionaries.

    This performs the same logical operations as the original notebook:
    - extracts time, radiation geometry, temperature, RH, wind and wind direction;
    - applies linear calibration to temperature and RH;
    - preserves NaN values for subsequent QC instead of dropping complete rows.
    """
    require_mat_keys(tower_mat, TOWER_REQUIRED_KEYS, "archivo de torre")
    require_mat_keys(sun_mat, SUN_REQUIRED_KEYS, "archivo de posición solar")

    data = {
        "year_tower": flatten_mat_array(tower_mat["year_data"], "year_data"),
        "month_tower": flatten_mat_array(tower_mat["month_data"], "month_data"),
        "day_tower": flatten_mat_array(tower_mat["day_data"], "day_data"),
        "hour_tower": flatten_mat_array(tower_mat["hour_data"], "hour_data"),
        "min_tower": flatten_mat_array(tower_mat["min_data"], "min_data"),
        "sec_tower": flatten_mat_array(tower_mat["seg_data"], "seg_data"),
        "zenith_tower": flatten_mat_array(sun_mat["zenith_angle"], "zenith_angle"),
        "azimuth_tower": flatten_mat_array(sun_mat["azimuth_angle"], "azimuth_angle"),
        "dir_wind": flatten_mat_array(tower_mat["dir_wind_02"], "dir_wind_02"),
    }

    for i in range(1, 7):
        data[f"temp_n{i}"] = flatten_mat_array(tower_mat[f"temp_n{i}"], f"temp_n{i}")
        data[f"RH_n{i}"] = flatten_mat_array(tower_mat[f"RH_n{i}"], f"RH_n{i}")
        data[f"wind_n{i}"] = flatten_mat_array(tower_mat[f"wind_n{i}"], f"wind_n{i}")

    lengths = {k: len(v) for k, v in data.items()}
    if len(set(lengths.values())) != 1:
        raise ValueError(
            "Longitudes inconsistentes entre variables. "
            "El código original con zip habría truncado datos silenciosamente. "
            f"Longitudes encontradas: {lengths}"
        )

    df = pd.DataFrame(data)
    df.replace("", np.nan, inplace=True)

    # Convert all sensor/time columns to numeric where possible.
    for col in df.columns:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    # Apply temperature calibration: y = m*x + b
    for col, (m, b) in temp_calib.items():
        if col in df.columns:
            df[col] = df[col] * m + b

    # Apply RH calibration: y = m*x + b
    for col, (m, b) in rh_calib.items():
        if col in df.columns:
            df[col] = df[col] * m + b

    return df


