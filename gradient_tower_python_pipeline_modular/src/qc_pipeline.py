def hypsometric_pressure(alt_m: float, T0: float = T0_STD, lapse: float = LAPSE, p0: float = P0) -> float:
    """Pressure from altitude using a standard-atmosphere hypsometric relation."""
    if alt_m < 0:
        raise ValueError("alt_m must be non-negative.")
    if lapse <= 0:
        raise ValueError("lapse must be positive.")
    base = 1.0 - lapse * alt_m / T0
    if base <= 0:
        raise ValueError("Invalid combination of alt_m, T0, and lapse.")
    expn = G / (RD * lapse)
    return float(p0 * base ** expn)


def es_tetens_pa(T_C: np.ndarray | pd.Series) -> np.ndarray:
    """Saturation vapor pressure over water using Tetens formula, in Pa."""
    T_C = np.asarray(T_C, dtype=float)
    return 610.94 * np.exp(17.625 * T_C / (T_C + 243.04))


def mixing_ratio(P: np.ndarray | float, e: np.ndarray | float) -> np.ndarray:
    """Mixing ratio r = 0.622 e / (P - e). Invalid denominators become NaN."""
    P = np.asarray(P, dtype=float)
    e = np.asarray(e, dtype=float)
    denom = P - e
    return np.where(denom > 0, 0.622 * e / denom, np.nan)


def specific_humidity_from_r(r: np.ndarray | pd.Series) -> np.ndarray:
    """Specific humidity q from mixing ratio r."""
    r = np.asarray(r, dtype=float)
    return np.where(r >= 0, r / (1.0 + r), np.nan)


def virtual_potential_temperature(T_C: np.ndarray, q: np.ndarray, P: np.ndarray | float) -> np.ndarray:
    """Virtual potential temperature in K."""
    T_K = np.asarray(T_C, dtype=float) + 273.15
    q = np.asarray(q, dtype=float)
    P = np.asarray(P, dtype=float)
    theta = T_K * (P0 / P) ** (RD / CP)
    return theta * (1.0 + 0.61 * q)


def circular_diff_deg(a: pd.Series, b: pd.Series) -> pd.Series:
    """Minimum signed angular difference a-b in degrees in [-180, 180)."""
    return ((a - b + 180.0) % 360.0) - 180.0


def circular_abs_diff_deg(a: pd.Series, b: pd.Series) -> pd.Series:
    """Minimum absolute angular difference in degrees."""
    return circular_diff_deg(a, b).abs()


def rolling_circular_center_deg(s: pd.Series, window: int, min_periods: Optional[int] = None) -> pd.Series:
    """Rolling circular center based on atan2(mean(sin), mean(cos))."""
    if min_periods is None:
        min_periods = max(3, window // 2)
    s_float = s.astype(float)
    rad = np.deg2rad(s_float)
    sin_mean = np.sin(rad).rolling(window, center=True, min_periods=min_periods).mean()
    cos_mean = np.cos(rad).rolling(window, center=True, min_periods=min_periods).mean()
    ang = np.rad2deg(np.arctan2(sin_mean, cos_mean)) % 360.0
    return pd.Series(ang, index=s.index)


def rolling_circular_mad_deg(
    s: pd.Series,
    window: int,
    center_deg: Optional[pd.Series] = None,
    min_periods: Optional[int] = None,
) -> pd.Series:
    """Rolling circular median absolute deviation around a circular center."""
    if min_periods is None:
        min_periods = max(3, window // 2)
    if center_deg is None:
        center_deg = rolling_circular_center_deg(s, window, min_periods=min_periods)
    dev = circular_abs_diff_deg(s.astype(float), center_deg.astype(float))
    return dev.rolling(window, center=True, min_periods=min_periods).median()


def rolling_median(s: pd.Series, window: int, min_periods: Optional[int] = None) -> pd.Series:
    if min_periods is None:
        min_periods = max(3, window // 2)
    return s.rolling(window, center=True, min_periods=min_periods).median()


def rolling_mad(s: pd.Series, window: int, min_periods: Optional[int] = None) -> pd.Series:
    if min_periods is None:
        min_periods = max(3, window // 2)
    med = rolling_median(s, window, min_periods=min_periods)
    dev = (s - med).abs()
    return dev.rolling(window, center=True, min_periods=min_periods).median()


