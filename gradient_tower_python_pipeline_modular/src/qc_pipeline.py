def read_calibration_matrix(path: str | Path, n_sensors: int = 6) -> pd.DataFrame:
    """
    Read calibration matrix with at least three columns.

    Expected columns by position:
        column 0: sensor/id or unused field
        column 1: slope m
        column 2: intercept b
    """
    p = require_file(path)
    df = pd.read_csv(p, header=None, sep=r"\s+", engine="python")
    if df.shape[0] < n_sensors or df.shape[1] < 3:
        raise ValueError(
            f"La matriz de calibración {p} debe tener al menos {n_sensors} filas y 3 columnas. "
            f"Forma encontrada: {df.shape}"
        )
    df = df.iloc[:n_sensors, :3].copy()
    df.columns = ["sensor", "m", "b"]
    df["m"] = pd.to_numeric(df["m"], errors="coerce")
    df["b"] = pd.to_numeric(df["b"], errors="coerce")
    if df[["m", "b"]].isna().any().any():
        raise ValueError(f"La matriz de calibración {p} contiene coeficientes no numéricos.")
    return df


def calibration_dict(calib_df: pd.DataFrame, prefix: str, n_sensors: int = 6) -> Dict[str, Tuple[float, float]]:
    """Build {column_name: (m, b)} for temp_n1..temp_n6 or RH_n1..RH_n6."""
    return {
        f"{prefix}{i+1}": (float(calib_df.loc[i, "m"]), float(calib_df.loc[i, "b"]))
        for i in range(n_sensors)
    }


